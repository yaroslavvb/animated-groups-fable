#!/usr/bin/env node
// build.mjs — bundle the page into ONE self-contained HTML file (dist/index.html). After The Folding's build.mjs.
//
// 1. MathJax, at build time: every formula becomes a static SVG (the page loads no script and no CDN).
//      - \( ... \) and \[ ... \] in src/index.template.html are typeset in place;
//      - src/formulas.mjs lists the pieces the app composes while it runs (the signature's glyphs, the readouts);
//        they are written to src/gen/math.js as { key: html }.
//    Needs mathjax-full 3.2.2: MATHJAX_HOME, default ~/.cache/mathjax-full-3.2.2 (npm i mathjax-full@3.2.2 there).
// 2. npx esbuild src/app.js --bundle --format=iife --minify, and the same for src/styles.css.
// 3. Both go into the template's placeholders; the shared glyph table goes right after <body>.
// 4. Checks: one file, one inline <script>, no external script / stylesheet / image, no URL except the ones allowed below.
//
//   node build.mjs [--no-minify] [--out dist/x.html] [--hide prove,name] [--template T --entry E --css A,B]
//     --out   write another file (a helper's build never touches dist/index.html)
//     --template, --entry, --css   another page from the same source: the Orbifold showcase is
//             node build.mjs --template src/showcase.template.html --entry src/showcase.js --css src/styles.css,src/showcase.css --out ../2026-11-17-orbifold-showcase/site/index.html
//     --hide  tabs whose button stays hidden in this build (a tab that is not ready is not published)

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import vm from 'node:vm';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const run = promisify(execFile);
const ROOT = path.dirname(fileURLToPath(import.meta.url));
const abs = (p) => path.resolve(ROOT, p);
const kb = (n) => (n / 1024).toFixed(1) + ' kB';
const count = (text, needle) => text.split(needle).length - 1;
const minify = !process.argv.includes('--no-minify');
const argOf = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 && process.argv[i + 1] ? process.argv[i + 1] : dflt; };
const OUT = argOf('--out', 'dist/index.html');
const HIDE = argOf('--hide', '').split(',').filter(Boolean);
const TEMPLATE = argOf('--template', 'src/index.template.html'), ENTRY = argOf('--entry', 'src/app.js'), CSS_FILES = argOf('--css', 'src/styles.css').split(',').filter(Boolean);
const CSS_SLOT = '/*__INLINE_CSS__*/', JS_SLOT = '/*__INLINE_JS__*/', CACHE_SLOT = '<!--__MATH_CACHE__-->';
// every URL the page may hold: its companions, the hub, the book on the tailnet
const ALLOW = [
  'https://spacesheep.dev/@yaroslavvb/',
  'http://intel/animated-groups/',
  'http://www.w3.org/2000/svg', 'http://www.w3.org/1999/xhtml', 'http://www.w3.org/1999/xlink', 'http://www.w3.org/1998/Math/MathML',
];

function fail(message) { console.error('build.mjs: ' + message); process.exit(1); }

async function esbuild(file, flags) {
  try {
    const { stdout, stderr } = await run('npx', ['--yes', 'esbuild', file, ...flags, '--log-level=warning'], { cwd: ROOT, maxBuffer: 256 * 1024 * 1024 });
    if (stderr.trim()) console.error(stderr.trimEnd());
    return stdout;
  } catch (err) {
    if (err.stderr) console.error(String(err.stderr).trimEnd());
    return fail(`esbuild failed on ${file}`);
  }
}

// ---- 1. MathJax
process.env.MATHJAX_HOME = process.env.MATHJAX_HOME || path.join(os.homedir(), '.cache/mathjax-full-3.2.2');
if (!fs.existsSync(path.join(process.env.MATHJAX_HOME, 'node_modules/mathjax-full'))) fail(`no mathjax-full under ${process.env.MATHJAX_HOME} (npm i mathjax-full@3.2.2 there, or set MATHJAX_HOME)`);
const { renderTex, renderHtml, fontCacheHtml, MATH_CSS } = await import('./tools/mathjax_render.mjs');
const { FORMULAS } = await import('./src/formulas.mjs');
const bank = {};
for (const [key, tex] of Object.entries(FORMULAS)) bank[key] = renderTex(tex, false);
fs.mkdirSync(abs('src/gen'), { recursive: true });
fs.writeFileSync(abs('src/gen/math.js'), '// GENERATED by build.mjs from src/formulas.mjs. Do not edit.\nexport const MATH = ' + JSON.stringify(bank, null, 1) + ';\n');

let shell = fs.readFileSync(abs(TEMPLATE), 'utf8');
// a second page takes the Symmetries tab's notes (on each kind of character, on the examples) from the main template,
// so that they are written once
const NOTES_SLOT = '<!--__SYM_NOTES__-->';
if (shell.includes(NOTES_SLOT)) {
  const notes = fs.readFileSync(abs('src/index.template.html'), 'utf8').split('\n').filter((l) => /id="sym-say"|data-when="sym(ex)?:/.test(l) && !/data-when="sym:none"/.test(l));
  if (notes.length < 20) fail(`only ${notes.length} notes found in src/index.template.html for ${NOTES_SLOT}`);
  shell = shell.replace(NOTES_SLOT, () => notes.join('\n'));
}
shell = shell.replace(/<!--(?!__MATH_CACHE__)[\s\S]*?-->\n?/g, '').replace(/\n{3,}/g, '\n\n');
for (const slot of [CSS_SLOT, JS_SLOT, CACHE_SLOT]) if (count(shell, slot) !== 1) fail(`the template must hold ${slot} exactly once (found ${count(shell, slot)})`);
for (const t of HIDE) {
  const tag = `data-tab="${t}" aria-selected="false">`;
  if (!shell.includes(tag)) fail(`--hide ${t}: no such tab button`);
  shell = shell.replace(tag, `data-tab="${t}" aria-selected="false" hidden>`);
}
shell = renderHtml(shell);
const formulas = renderHtml.lastCount + Object.keys(bank).length;

// ---- 2. the bundle
const [jsRaw, ...cssParts] = await Promise.all([
  esbuild(abs(ENTRY), ['--bundle', '--format=iife', ...(minify ? ['--minify'] : [])]),
  ...CSS_FILES.map((f) => esbuild(abs(f), minify ? ['--minify'] : [])),
]);
const cssRaw = cssParts.map((c) => c.trim()).join('\n');
if (!jsRaw.trim() || !cssRaw.trim()) fail('an empty bundle');
let js = jsRaw.trim().replace(/<\/script/gi, '<\\/script').replace(/<!--/g, '<\\!--');
try { new vm.Script(js, { filename: 'bundle.js' }); } catch (err) { fail('the escaped bundle no longer parses: ' + err.message); }
const css = (cssRaw.trim() + MATH_CSS.replace(/\n/g, '')).replace(/<\/style/gi, '<\\/style');

// ---- 3. one file
const html = shell.replace(JS_SLOT, () => js).replace(CSS_SLOT, () => css).replace(CACHE_SLOT, () => fontCacheHtml());

// ---- 4. checks
const problems = [];
const lower = html.toLowerCase();
if (!/^<!doctype html>/i.test(html.trimStart())) problems.push('the page does not start with <!doctype html>');
if (count(lower, '<script') !== 1 || count(lower, '</script') !== 1) problems.push('the page must hold exactly one <script>');
if (count(lower, '</style') !== 1) problems.push('the page must hold exactly one <style>');
if (/<script[^>]*\ssrc\s*=/.test(lower)) problems.push('a script file is loaded');
if (/<link\b/.test(lower)) problems.push('a <link> is left');
if (/<(?:img|iframe|video|audio|source|object|embed)\b/.test(lower)) problems.push('an external resource is embedded');
if (/@import\b/i.test(css)) problems.push('the CSS has an @import');
if (/url\(\s*["']?(?!data:|#)/i.test(css)) problems.push('the CSS has a url() that is not a data: URI');
const urls = [...new Set(html.match(/\b(?:https?|wss?|ftp):\/\/[^\s"'`<>)\\]+/gi) || [])].filter((u) => !ALLOW.some((p) => u.startsWith(p)));
if (urls.length) problems.push('URLs that are not on the allow list:\n      ' + urls.join('\n      '));
if (problems.length) fail(OUT + ' was NOT written:\n  - ' + problems.join('\n  - '));

fs.mkdirSync(path.dirname(abs(OUT)), { recursive: true });
fs.writeFileSync(abs(OUT), html);
const bytes = Buffer.byteLength(html);
console.log(`built ${OUT}${HIDE.length ? ' (hidden: ' + HIDE.join(', ') + ')' : ''}${minify ? '' : ' (not minified)'}: ${kb(bytes)} (${kb(zlib.gzipSync(html, { level: 9 }).length)} gzipped), js ${kb(Buffer.byteLength(js))}, css ${kb(Buffer.byteLength(css))}, ${formulas} formulas typeset`);
