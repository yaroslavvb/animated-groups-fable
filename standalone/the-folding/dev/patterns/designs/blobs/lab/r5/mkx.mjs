//   node lab/r5/mkx.mjs > lab/r5/vx.json
const L = Math.hypot(4.54, 0.851), ax = 4.54 / L, ay = 0.851 / L;          // along the mirrors, in the frame
const P = (s, t) => [s * ax - t * ay, s * ay + t * ax];
