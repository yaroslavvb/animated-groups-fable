#!/usr/bin/env node
// build-dev.mjs — the shell owner's build.
//   node dev/shell/build-dev.mjs            -> dev/shell/index.html
//   node dev/shell/build-dev.mjs --site     -> site/index.html (only the shell owner builds there)
//   node dev/shell/build-dev.mjs --off      -> dev/shell/index-off.html, the Surface switched off (stand-ins for its three modules)
//   node dev/shell/build-dev.mjs --tutorial -> dev/shell/index-tutorial.html, with src/tutorial.html pasted between the
//                                              template's two markers (in a copy of the template kept in dev/shell/: a
//                                              rehearsal of what the integrator does; src/ is not touched)
// When every module page.js imports is in src/, this runs the SPEC 2.2 command as it is. When one is missing (another
// owner has not landed it yet), or with --off, the entry is a rewritten copy of src/page.js (dev/shell/page.dev.js)
// whose missing imports point at stand-ins that export null: the page then shows its quiet "surface loading" line.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../..');                         // standalone/pqrs-pillows
const cos = resolve(root, '../classification-of-surfaces');
const args = process.argv.slice(2), site = args.includes('--site'), off = args.includes('--off'), tut = args.includes('--tutorial');
const out = site ? resolve(root, 'site/index.html') : resolve(here, off ? 'index-off.html' : tut ? 'index-tutorial.html' : 'index.html');
let template = '../pqrs-pillows/src/page.template.html';
if (tut) {
  const t = readFileSync(resolve(root, 'src/page.template.html'), 'utf8'), a = t.indexOf('<!-- TUTORIAL:BEGIN -->'), b = t.indexOf('<!-- TUTORIAL:END -->');
  if (a < 0 || b < a) { console.error('build-dev: the template has no TUTORIAL markers'); process.exit(2); }
  writeFileSync(resolve(here, 'page.template.tutorial.html'), `${t.slice(0, a)}<!-- TUTORIAL:BEGIN -->\n${readFileSync(resolve(root, 'src/tutorial.html'), 'utf8')}\n${t.slice(b)}`);
  template = resolve(here, 'page.template.tutorial.html');
}

const SURFACE = { 'surface-model.js': 'createSurfaceModel', 'surface-pane.js': 'createSurfacePane', 'print3d.js': 'createPrint3d' };
const missing = Object.keys(SURFACE).filter((f) => off || !existsSync(resolve(root, 'src', f)));
let entry = '../pqrs-pillows/src/page.js';
if (missing.length) {
  mkdirSync(resolve(here, 'standin'), { recursive: true });
  let src = readFileSync(resolve(root, 'src/page.js'), 'utf8');
  src = src.replace(/from '\.\.\/\.\.\//g, "from '../../../");          // src/ -> dev/shell/: one level deeper
  src = src.replace(/from '\.\/([\w-]+\.js)'/g, (m, f) => `from '${missing.includes(f) ? `./standin/${f}` : `../../src/${f}`}'`);
  for (const f of missing) writeFileSync(resolve(here, 'standin', f), `// stand-in: src/${f} is not there yet${off ? ' (or the build was asked for with --off)' : ''}\nexport const ${SURFACE[f]} = null;\n`);
  writeFileSync(resolve(here, 'page.dev.js'), `// GENERATED by build-dev.mjs from src/page.js (stand-ins for: ${missing.join(', ')}). Do not edit.\n${src}`);
  entry = resolve(here, 'page.dev.js');
  console.log(`build-dev: STAND-INS for ${missing.join(', ')}: the Surface pane shows its "surface loading" line`);
}
const cmd = ['build.mjs', '--template', template, '--entry', entry,
  '--css', 'src/styles.css,../two-features-two-handles/src/page.css,../pqrs-pillows/src/page.css', '--out', out, ...(args.includes('--no-minify') ? ['--no-minify'] : [])];
const r = spawnSync('node', cmd, { cwd: cos, stdio: 'inherit' });
process.exit(r.status ?? 1);
