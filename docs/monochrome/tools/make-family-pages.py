def thumb_url(entry_id):
    return 'data/thumbs/' + entry_id.replace(':', '-') + '.png'


def best_of(entries):
    """The still a card shows: a featured picture if the family has one, else the
    most legible. Ties break on the id so the stamp is deterministic."""
    return sorted(entries, key=lambda e: (not e['featured'], -e['metrics']['score'], e['id']))[0]


def tier_of(entry):
    """v2 says outright which of the three tiers a reading is in; on v1 the
    working discriminator is the measured half-period law, and the threshold is
    the control by construction."""
    if entry.get('tier') in ('strict', 'broad', 'control'):
        return entry['tier']
    if entry['kind'] == 'threshold':
        return 'control'
    return 'strict' if entry['laws'].get('halfPeriod', [0, 0])[1] == 1 else 'broad'


def family_stats(atlas):
    """Per family: the pictures (distinct fields), the readings by tier, the
    equations, the lattice and the still. Counted the way the explorer counts."""
    fields = atlas['fields']
    stats = {}
    for fam in ORDER:
        here = [e for e in atlas['entries'] if fam in fields[e['field']]['families']]
        keys = sorted({e['field'] for e in here})
        models = {}
        for key in keys:
            models[fields[key]['model']] = models.get(fields[key]['model'], 0) + 1
        gids = sorted({g for key in keys for g in fields[key]['groupIds']
                       if g in FAMILY_GROUPS.get(fam, ())})
        tiers = {t: sum(1 for e in here if tier_of(e) == t) for t in ('strict', 'broad', 'control')}
        lattices = sorted({fields[key]['lattice'] for key in keys})
        stats[fam] = {
            'pictures': len(keys), 'readings': len(here), 'tiers': tiers,
            'strict': tiers['strict'],
            # NOT the tier: the tier says whether s is a symmetry of the field,
            # this says whether the picture is antisymmetric in time, and on the
            # phase-symmetric equations the second is true far more often.
            'halfPeriodExact': sum(1 for e in here
                                   if e['laws'].get('halfPeriod', [0, 0])[1] == 1),
            'groups': gids, 'lattice': lattices[0] if len(lattices) == 1 else 'mixed',
            'models': models, 'entries': here,
        }
    # The seventeen covers have to be seventeen DIFFERENT pictures: a field
    # filed under several families would otherwise be the best-scoring picture
    # of two of them, and ∗333 and ∗632 shipped the same hexagon-and-ring tiling
    # side by side in the directory whose whole job is to tell them apart.
    # Smallest families choose first, because they have the least to choose from.
    taken = set()
    for fam in sorted(ORDER, key=lambda f: len(stats[f]['entries'])):
        here = [e for e in stats[fam]['entries'] if e['id'] not in taken
                and thumb_url(e['id']) not in taken]
        pick = best_of(here or stats[fam]['entries']) if stats[fam]['entries'] else None
        stats[fam]['still'] = thumb_url(pick['id']) if pick else None
        if pick:
            taken.add(thumb_url(pick['id']))
    for fam in ORDER:
        del stats[fam]['entries']
    return stats


