def nav(prefix, here):
    """The shared site header, one definition for all eighteen pages.

    `here` is the href (relative to docs/) of the page's own link, which gets
    `class="here"`; `site-header.js` turns that into aria-current="page".
    """
    out = []
    for label, links in NAV_GROUPS:
        classes = ' navgroup-superseded' if label == 'Superseded' else ''
        out.append(f'      <span class="navgroup{classes}">')
        out.append(f'        <span class="navgroup-label">{label}</span>')
        for href, text in links:
            mark = ' class="here"' if href == here else ''
            out.append(f'        <a href="{prefix}{href}"{mark}>{text}</a>')
        out.append('      </span>')
    return '\n'.join(out)


