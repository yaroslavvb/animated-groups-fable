def main():
    global PLUME_STILL, WEAVE_STILL, FAMILY_GROUPS
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--check', action='store_true', help='diff against the files on disk and exit 1 on any difference')
    args = ap.parse_args()
    atlas, groups = load()
    if atlas.get('schema') not in ('monochrome-atlas-v1', 'monochrome-atlas-v2'):
        raise SystemExit(f"unsupported catalog schema {atlas.get('schema')}")
    FAMILY_GROUPS = {fam: tuple(g['id'] for g in groups['groups'] if g['family'] == fam) for fam in ORDER}

    # The two named classics name themselves: the builder stamps `shippedPage`
    # on exactly the entries the site already publishes as their own pages.
