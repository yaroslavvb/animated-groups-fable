    # stamps `shippedPage` on the two entries, and the field shas are the last
    # resort so a catalog that drops both still stamps.
    classics = atlas.get('classics') or {}
    shipped = [(str(e.get('shippedPage', {}).get('page', '')), e['id'])
               for e in atlas['entries'] if isinstance(e.get('shippedPage'), dict)]
    def still_for(name, fallback_field):
        for item in classics.values():
            if name in str(item.get('page', '')) and item.get('entry'):
                return thumb_url(item['entry'])
        for page, entry_id in shipped:
            if name in page:
                return thumb_url(entry_id)
        for e in atlas['entries']:
            if e['field'] == fallback_field and e['kind'] == 'half-period':
                return thumb_url(e['id'])
        raise SystemExit(f'no still for {name}')
    PLUME_STILL = still_for('plume', '731aa45654d4')
    WEAVE_STILL = still_for('weave', '459f00246aed')

    stats = family_stats(atlas)
    missing = [fam for fam in ORDER if not stats[fam]['pictures']]
    if missing:
        raise SystemExit(f'the catalog has no pictures for {", ".join(missing)}; refusing to stamp')

    wanted = {os.path.join(MONO, 'index.html'): landing(atlas, groups, stats)}
    for index, fam in enumerate(ORDER):
        wanted[os.path.join(MONO, fam, 'index.html')] = family_page(fam, index, atlas, groups, stats)

    differing = []
    for path, text in sorted(wanted.items()):
        current = None
        if os.path.exists(path):
            with open(path, encoding='utf-8') as fh:
                current = fh.read()
        if current == text:
            continue
        differing.append(os.path.relpath(path, DOCS))
        if not args.check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8') as fh:
                fh.write(text)
