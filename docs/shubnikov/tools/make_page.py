def counts_table(census: dict) -> str:
    rows = []
    families = census["families"]
    for lattice, members in LATTICE_RUNS:
        rows.append(f'<tr class="lattice-head"><th colspan="7" scope="colgroup">{E(lattice)} lattice</th></tr>')
        for hm in members:
            fam = families[hm]
            by = fam["byN"]
            cells = "".join(
                f'<td data-label="n={n}">{int(by.get(str(n), 0))}</td>' for n in NS
            )
            rows.append(
                f'<tr><th scope="row"><a href="#{E(hm)}">{E(hm)}</a>'
                f'<span class="orbifold">{E(fam["orbifold"])}</span></th>'
                f'{cells}'
                f'<td data-label="total"><b>{fam["total"]}</b></td>'
                f'<td data-label="invisible to the clock">{fam["ct0"]}</td></tr>'
            )
    totals = census["totals"]
    foot = "".join(f'<td data-label="n={n}">{totals["byN"][str(n)]}</td>' for n in NS)
    return (
        '<div class="shub-table-wrap"><table class="shub-counts">'
        '<caption class="visually-hidden">Cyclic colourings per wallpaper group and number of colours</caption>'
        '<thead><tr><th scope="col">Group</th>'
        + "".join(f'<th scope="col">n = {n}</th>' for n in NS)
        + '<th scope="col">total</th><th scope="col">cₜ = 0</th></tr></thead>'
        '<tbody>' + "".join(rows) + '</tbody>'
        f'<tfoot><tr><th scope="row">All 68 films</th>{foot}'
        f'<td data-label="total"><b>{totals["all"]}</b></td>'
        f'<td data-label="invisible to the clock">{totals["ct0"]}</td></tr></tfoot>'
        '</table></div>'
    )


def film_panel(census: dict, prose: dict, gid: str, only: bool, index: int = 0) -> str:
    film = census["films"][gid]
    counts = film_counts(film)
    by_key = {}
    for cls in census["classes"]:
        if cls["gid"] == gid:
            by_key.setdefault((cls["n"], cls["key"]), 0)
            by_key[(cls["n"], cls["key"])] += 1

    # The per-film prose — the description of the film group, the note under
    # each colour count and each clock group — is written by shub-app.mjs from
    # the census and the prose island, so the same sentence is not stamped
    # sixty-eight times into the file.
    sections = []
    for n in NS:
        total = counts[n]
        empty = total == 0
        open_attr = " open" if n == 2 and not empty else ""
        title = prose["N_TITLES"].get(n, f"{n} colours")
        groups = "".join(
            f'<section class="shub-ck" data-key="{key}">'
            f'<h4>{prose["CLOCK_TITLES"][key]} <b>{by_key[(n, key)]}</b></h4>'
            f'<div class="shub-grid" data-grid></div></section>'
            for key in KEYS if by_key.get((n, key))
        )
        body = groups if not empty else (
            '<p class="shub-empty">No cyclic colouring of this film group uses this many colours.</p>'
        )
        sections.append(
            f'<details class="shub-n" data-n="{n}"'
            f'{" data-empty=\"true\"" if empty else ""}'
            f' id="sec-{E(gid)}-n{n}"{open_attr}>'
            f'<summary>{title} <b>{"none" if empty else total}</b></summary>'
            f'{body}</details>'
        )

    hidden = "" if only or index == 0 else " hidden"
    labelled = "" if only else f' role="tabpanel" aria-labelledby="filmtab-{E(gid)}"'
    return (
        f'<div class="shub-film" id="film-{E(gid)}" data-film="{E(gid)}"{labelled}{hidden}>'
        f'{"".join(sections)}'
        f'</div>'
    )


def family_panel(census: dict, prose: dict, hm: str, index: int) -> str:
    fam = census["families"][hm]
    films = fam["films"]
    note = prose["FAMILY_NOTES"].get(hm, "")
    tabs = ""
    if len(films) > 1:
        buttons = []
        for i, gid in enumerate(films):
            film = census["films"][gid]
            total = film_total(film)
            selected = "true" if i == 0 else "false"
            buttons.append(
                f'<button type="button" class="shub-filmtab" role="tab" id="filmtab-{E(gid)}"'
                f' data-film="{E(gid)}" aria-controls="film-{E(gid)}" aria-selected="{selected}"'
                f' tabindex="{0 if i == 0 else -1}"'
                f' data-label-stem="{E(gid)}, {E(film["signature"])}, space group {E(film["sgName"])}"'
                f' aria-label="{E(gid)}, {E(film["signature"])}, space group {E(film["sgName"])}, '
                f'{total} colourings">'
                f'<span class="sig">{E(film["signature"])}</span>'
                f'<span class="sub">{E(gid)} · {E(film["sgName"])} · N={film["N"]} · {total}</span>'
                f'</button>'
            )
        tabs = (
            f'<div class="shub-filmtabs" role="tablist" aria-label="Film groups over {E(hm)}">'
            + "".join(buttons) + '</div>'
        )
    panels = "".join(
        film_panel(census, prose, gid, only=len(films) == 1, index=i)
        for i, gid in enumerate(films)
    )
    return (
        f'<section class="shub-panel" id="panel-{E(hm)}" role="tabpanel" aria-labelledby="tab-{E(hm)}"'
        f' data-family="{E(hm)}"{"" if index == 0 else " hidden"}>'
        f'<div class="shub-family-head"><h2>{E(hm)}</h2>'
        f'<span class="orb">{E(fam["orbifold"])}</span>'
        f'<span class="lat">{E(CRYSTAL_SYSTEM[hm])} lattice · {len(films)} film group'
        f'{"s" if len(films) != 1 else ""} · {fam["total"]} colourings</span></div>'
        + (f'<p class="shub-family-note">{note}</p>' if note else "")
        + tabs + panels + '</section>'
    )


def tabstrip(census: dict) -> str:
    groups = []
    first = True
    for lattice, members in LATTICE_RUNS:
        buttons = []
        for hm in members:
            fam = census["families"][hm]
            selected = "true" if first else "false"
            tabindex = 0 if first else -1
            buttons.append(
                f'<button type="button" class="shub-tab" role="tab" id="tab-{E(hm)}"'
                f' data-family="{E(hm)}" aria-controls="panel-{E(hm)}" aria-selected="{selected}"'
                f' tabindex="{tabindex}"'
                f' data-label-stem="{E(hm)}, orbifold {E(fam["orbifold"])}, {E(lattice.lower())} lattice"'
                f' aria-label="{E(hm)}, orbifold {E(fam["orbifold"])}, {E(lattice.lower())} lattice, '
                f'{fam["total"]} colourings">'
                f'<span class="hm">{E(hm)}</span>'
                f'<span class="orb">{E(fam["orbifold"])}</span>'
                f'<span class="n" data-tabcount>{fam["total"]}</span>'
                f'</button>'
            )
            first = False
        groups.append(
            f'<span class="shub-tabgroup" role="presentation">'
            f'<span class="shub-tabgroup-label" aria-hidden="true">{E(lattice)}</span>'
            + "".join(buttons) + '</span>'
        )
    return (
        '<div class="shub-tabstrip" role="tablist" aria-label="Wallpaper groups">'
        + "".join(groups) + '</div>'
    )


