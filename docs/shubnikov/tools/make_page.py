def check_wave_budget(census: dict) -> None:
    """The shader's uWaves array is fixed; the CPU twin's is not.

    A census that asked for more waves than the shader holds would draw one
    picture on the GPU and a different one on the CPU, with no error anywhere.
    The array size is the only thing tying the two together, so it is read from
    the renderer rather than repeated here.
    """
    source = (ROOT / "shub-render.mjs").read_text()
    found = re.search(r"export const MAX_WAVES = (\d+)", source)
    if not found:
        raise SystemExit("shub-render.mjs: cannot find MAX_WAVES")
    limit = int(found.group(1))
    wanted = int(census["model"]["maxModes"])
    if wanted > limit:
        raise SystemExit(
            f"census asks for {wanted} waves but the shader holds {limit}: "
            f"raise MAX_WAVES in shub-render.mjs"
        )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if index.html has drifted")
    args = parser.parse_args()

    census = json.loads(CENSUS.read_text())
    if census.get("schema") != "shubnikov-census-v1":
        raise SystemExit(f"census: unexpected schema {census.get('schema')!r}")
    if HERO not in {cls["id"] for cls in census["classes"]}:
        raise SystemExit(f"census: no class {HERO!r} for the opening picture")
    check_wave_budget(census)
    prose, have_prose = load_prose()
    names_summary = None
    if NAMES.exists():
        names = json.loads(NAMES.read_text())
        if names.get("schema") != "shubnikov-names-v1":
            raise SystemExit(f"names: unexpected schema {names.get('schema')!r}")
        names_summary = names.get("summary") or {}
    prose = fill_placeholders(prose, names_summary)
    text = build(census, prose, NAMES.exists())

    if args.check:
        if not OUT.exists():
            print("index.html is missing")
            return 1
        if OUT.read_text() != text:
            print("index.html has drifted from a fresh stamp")
            return 1
        print(f"index.html matches a fresh stamp ({len(text) // 1024} KB)")
        return 0

    OUT.write_text(text)
    print(
        f"wrote {OUT.relative_to(ROOT.parent)} — {len(text) // 1024} KB, "
        f"{len(census['order'])} families, {len(census['films'])} films, "
        f"{census['totals']['all']} colourings"
        f"{'' if have_prose else ' (prose.py absent: placeholder prose)'}"
        f"{'' if NAMES.exists() else ' (names.json absent)'}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
