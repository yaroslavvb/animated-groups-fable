def load_prose():
    prose = dict(DEFAULTS)
    sys.path.insert(0, str(HERE))
    try:
        import prose as module  # type: ignore
    except Exception:
        return prose, False
    finally:
        sys.path.pop(0)
    for key in DEFAULTS:
        if hasattr(module, key):
            value = getattr(module, key)
            if isinstance(DEFAULTS[key], dict) and isinstance(value, dict):
                merged = dict(DEFAULTS[key])
                merged.update({int(k) if str(k).isdigit() else k: v for k, v in value.items()})
                prose[key] = merged
            else:
                prose[key] = value
    return prose, True


PLACEHOLDER = "{{TWO_COLOUR_TYPES}}"
# the sentence the placeholder sits in, so it can be cut whole when the
# number is not available: from a tag boundary or full stop to the next one
SENTENCE = re.compile(r"\s*[^.<>]*\{\{TWO_COLOUR_TYPES\}\}[^.<>]*\.")


def fill_placeholders(value, summary):
    """Substitute {{TWO_COLOUR_TYPES}} everywhere in the prose, or cut its sentence."""
    if isinstance(value, dict):
        return {k: fill_placeholders(v, summary) for k, v in value.items()}
    if isinstance(value, list):
        return [fill_placeholders(v, summary) for v in value]
    if not isinstance(value, str) or PLACEHOLDER not in value:
        return value
    realised = (summary or {}).get("twoColourTypesRealised")
    if realised is None:
        return SENTENCE.sub("", value)
    # The prose reads "… realise {{TWO_COLOUR_TYPES}} two-colour wallpaper types".
    total = (summary or {}).get("twoColourTypesTotal", 46)
    phrase = f"all {total}" if realised == total else f"{realised} of the {total}"
    extra = ""
    if not (summary or {}).get("cyclicColourGroupsUnrealised", ["?"]):
        n = summary.get("distinctColourGroups")
        extra = (f" Adding the clock-invisible colourings with three, four and six colours, every "
                 f"cyclic plane colour group with two, three, four or six colours appears, {n} in all.")
    return value.replace(PLACEHOLDER + " two-colour wallpaper types.",
                         f"{phrase} two-colour wallpaper types.{extra}").replace(PLACEHOLDER, phrase)


