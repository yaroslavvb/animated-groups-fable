def prose_island(prose: dict) -> str:
    """The prose the page needs per film, handed to shub-app.mjs as data.

    These four sentences and two notes would otherwise be stamped six hundred
    times over — once under every colour count of every film — so the file
    carries one copy and the script puts them where they belong.
    """
    payload = {
        "nNote": {str(n): prose["N_NOTES"].get(n, "") for n in NS},
        "keyNote": {key: prose["CLOCK_NOTES"].get(key, "") for key in KEYS},
    }
    text = json.dumps(payload, ensure_ascii=False).replace("</", "<\\/")
    return f'<script type="application/json" id="shub-prose">{text}</script>'


