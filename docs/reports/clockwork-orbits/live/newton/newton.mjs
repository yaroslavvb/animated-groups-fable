// newton.mjs — twisted shooting solved by Newton–GMRES, in the browser.
//
// The equation being solved is the repository's (rdlab.twisted_residual / rpo_polish):
//
//     F(q0, T) = [ P_kernel( S_g Phi_{T/m}(q0) - q0 ) ,  <q0 - q_ref, f(q_ref)> ]  =  0
//
//   * Phi_s is the RK4 flow of the Brusselator for time s (no projection);
//   * S_g is the exact index permutation of the primitive generator g, the operation
//     with tau = 1/m (m = 3 for g227) — a 120-degree rotation about a screw centre;
//   * P_kernel averages over the tau = 0 operations, so the unknown state keeps the
//     instantaneous (same-time) symmetry;
//   * the last row is the phase condition: it removes the one-parameter freedom of
//     sliding the time origin along the orbit, which would otherwise make the
//     Jacobian singular.
//
// A zero means q(M x + v, t + T/3) = q(x, t): the whole movie is generated by one
// third of a period plus a rotation.  That is the clockwork.
//
// The Jacobian is never formed.  GMRES only needs directional derivatives, and each
// one costs one extra trajectory:  J v ~ (F(z + sigma v) - F(z)) / sigma.
// This is why the search is dominated by "how many times did we integrate T/3".

import { makeFlow, applyMap, projectKernel, makeRhs, counters } from './core.mjs';

/** Builds the residual function for one mesh/parameter set.
 *  Unknowns: the field (optionally reduced to one value per kernel orbit) and log T.
 *  `reduced: true` genuinely shrinks the problem — for g227 at N = 36 from
 *  2*1296 + 1 = 2593 unknowns to 2*434 + 1 = 869 (434, not 1296/3 = 432, because the
 *  rotation has three fixed nodes on the torus). */
export function makeResidual(mesh, ch, p, { reduced = true, dt = null, qRef = null } = {}) {
  const flow = makeFlow(mesh, p);
  const rhs = makeRhs(mesh, p);
  const n = mesh.n, m = 2 * n;
  const { reps, expand, count } = ch.reduction;
  const dim = (reduced ? 2 * count : m) + 1;

  // scratch: `state` holds the unpacked (kernel-projected) field, `proj` the projected
  // residual.  They must be different arrays — projecting the residual into the array that
  // still holds the state would corrupt the phase condition.
  const full = new Float64Array(m), state = new Float64Array(m), evolved = new Float64Array(m),
    rotated = new Float64Array(m), proj = new Float64Array(m);

  // the phase-condition reference direction: the time derivative at the seed
  const ref = projectKernel(ch, qRef);
  const tangent = rhs(ref, new Float64Array(m));
  let tn = 0; for (let i = 0; i < m; i++) tn += tangent[i] * tangent[i];
  tn = Math.sqrt(tn) || 1;
  for (let i = 0; i < m; i++) tangent[i] /= tn;

  const unpackField = (z, out = full) => {
    if (reduced) {
      for (let i = 0; i < n; i++) { out[i] = z[expand[i]]; out[n + i] = z[count + expand[i]]; }
      return out;                     // already kernel-invariant by construction
    }
    for (let i = 0; i < m; i++) out[i] = z[i];
    return projectKernel(ch, out, out === full ? state : new Float64Array(m));
  };

  const pack = (field, T, z = new Float64Array(dim)) => {
    if (reduced) {
      for (let k = 0; k < count; k++) { z[k] = field[reps[k]]; z[count + k] = field[n + reps[k]]; }
    } else {
      for (let i = 0; i < m; i++) z[i] = field[i];
    }
    z[dim - 1] = Math.log(T);
    return z;
  };

  function residual(z, out = new Float64Array(dim)) {
    const q = unpackField(z);
    const T = Math.exp(z[dim - 1]);
    flow(q, T / ch.order, evolved, { dt });
    applyMap(evolved, ch.generatorMap, n, rotated);
    for (let i = 0; i < m; i++) rotated[i] -= q[i];
    const r = projectKernel(ch, rotated, proj);
    if (reduced) {
      for (let k = 0; k < count; k++) { out[k] = r[reps[k]]; out[count + k] = r[n + reps[k]]; }
    } else {
      for (let i = 0; i < m; i++) out[i] = r[i];
    }
    let phase = 0;
    for (let i = 0; i < m; i++) phase += (q[i] - ref[i]) * tangent[i];
    out[dim - 1] = phase;
    return out;
  }

  /** rms of the shooting part of the residual — the number the page plots. */
  const rms = f => {
    let s = 0; for (let i = 0; i < f.length - 1; i++) s += f[i] * f[i];
    return Math.sqrt(s / (f.length - 1));
  };

  return { residual, pack, unpackField, dim, rms, count, reduced, tangent, ref, flow };
}

const norm2 = v => { let s = 0; for (let i = 0; i < v.length; i++) s += v[i] * v[i]; return Math.sqrt(s); };

/** Plain GMRES (modified Gram–Schmidt + Givens rotations), no restarts.
 *  `matvec` is the finite-difference Jacobian action.  Stops when the relative
 *  residual falls below `rtol` or after `maxiter` Krylov vectors. */
function gmres(matvec, b, { maxiter = 30, rtol = 0.1 } = {}) {
  const dim = b.length;
  const bnorm = norm2(b);
  if (bnorm === 0) return { x: new Float64Array(dim), iterations: 0, residual: 0 };
  const V = [], H = [], cs = [], sn = [];
  const g = new Float64Array(maxiter + 1);
  g[0] = bnorm;
  V.push(Float64Array.from(b, x => x / bnorm));
  let k = 0, resid = bnorm;
  for (; k < maxiter; k++) {
    const w = matvec(V[k]);
    const h = new Float64Array(maxiter + 1);
    for (let i = 0; i <= k; i++) {                    // modified Gram–Schmidt
      let d = 0; for (let j = 0; j < dim; j++) d += w[j] * V[i][j];
      h[i] = d;
      for (let j = 0; j < dim; j++) w[j] -= d * V[i][j];
    }
    const beta = norm2(w);                            // the new subdiagonal entry
    h[k + 1] = beta;
    for (let i = 0; i < k; i++) {                     // apply earlier rotations
      const t = cs[i] * h[i] + sn[i] * h[i + 1];
      h[i + 1] = -sn[i] * h[i] + cs[i] * h[i + 1];
      h[i] = t;
    }
    const r = Math.hypot(h[k], h[k + 1]);
    cs[k] = h[k] / r; sn[k] = h[k + 1] / r;
    h[k] = r; h[k + 1] = 0;
    g[k + 1] = -sn[k] * g[k]; g[k] = cs[k] * g[k];
    H.push(h);
    resid = Math.abs(g[k + 1]);
    if (resid <= rtol * bnorm) { k++; break; }
    if (beta < 1e-14 * bnorm) { k++; break; }         // happy breakdown
    if (k + 1 < maxiter) { const u = new Float64Array(dim); for (let j = 0; j < dim; j++) u[j] = w[j] / beta; V.push(u); }
  }
  // back substitution
  const y = new Float64Array(k);
  for (let i = k - 1; i >= 0; i--) {
    let s = g[i];
    for (let j = i + 1; j < k; j++) s -= H[j][i] * y[j];
    y[i] = s / H[i][i];
  }
  const x = new Float64Array(dim);
  for (let i = 0; i < k; i++) for (let j = 0; j < dim; j++) x[j] += y[i] * V[i][j];
  return { x, iterations: k, residual: resid / bnorm };
}

/** Inexact Newton with a finite-difference Krylov Jacobian, Eisenstat–Walker forcing
 *  and an Armijo backtracking line search — the same scheme scipy's
 *  root(method='krylov') uses, so it lands on the same orbits as the Python code.
 *
 *  `onStep(info)` is called after every Newton iteration; the page draws with it.
 *  The whole thing is a generator so the browser can paint between steps. */
export function* newtonKrylov(res, z0, { maxiter = 40, tol = 1e-11, innerMaxiter = 30, rdiff = Math.sqrt(2.220446049250313e-16) } = {}) {
  const dim = res.dim;
  let z = Float64Array.from(z0);
  let F = Float64Array.from(res.residual(z));
  let fn = norm2(F);
  let eta = 1e-3;
  const gamma = 0.9, etaMax = 0.9999, etaThreshold = 0.1;
  let flows0 = counters.flowCalls;

  yield { iteration: 0, residualRms: res.rms(F), residualNorm: fn, T: Math.exp(z[dim - 1]), z, F, flows: counters.flowCalls - flows0, inner: 0, step: 0 };

  for (let it = 1; it <= maxiter; it++) {
    const zn = norm2(z);
    const omega = rdiff * Math.max(1, zn);
    const probe = new Float64Array(dim);
    const matvec = v => {
      const vn = norm2(v);
      if (vn === 0) return new Float64Array(dim);
      const sc = omega / vn;
      for (let i = 0; i < dim; i++) probe[i] = z[i] + sc * v[i];
      const Fp = res.residual(probe);
      const out = new Float64Array(dim);
      for (let i = 0; i < dim; i++) out[i] = (Fp[i] - F[i]) / sc;
      return out;
    };
    const rhsVec = Float64Array.from(F, x => -x);
    const sol = gmres(matvec, rhsVec, { maxiter: innerMaxiter, rtol: eta });

    // Armijo backtracking on ||F||
    let step = 1, accepted = false, Fnew = null, fnNew = fn;
    const trial = new Float64Array(dim);
    while (step >= 1 / 64) {
      for (let i = 0; i < dim; i++) trial[i] = z[i] + step * sol.x[i];
      Fnew = Float64Array.from(res.residual(trial));
      fnNew = norm2(Fnew);
      if (fnNew < (1 - 1e-4 * step) * fn) { accepted = true; break; }
      step /= 2;
    }
    if (!accepted) {               // take the smallest step anyway and let the next step judge
      for (let i = 0; i < dim; i++) trial[i] = z[i] + step * sol.x[i];
      Fnew = Float64Array.from(res.residual(trial));
      fnNew = norm2(Fnew);
    }
    const fnPrev = fn;
    z = Float64Array.from(trial); F = Fnew; fn = fnNew;

    // Eisenstat–Walker forcing term for the next inner solve
    const etaA = gamma * (fn * fn) / (fnPrev * fnPrev);
    eta = gamma * eta * eta < etaThreshold ? Math.min(etaMax, etaA) : Math.min(etaMax, Math.max(etaA, gamma * eta * eta));

    const info = {
      iteration: it, residualRms: res.rms(F), residualNorm: fn, T: Math.exp(z[dim - 1]),
      z, F, inner: sol.iterations, step, eta, flows: counters.flowCalls - flows0,
      converged: res.rms(F) <= tol,
    };
    yield info;
    if (info.converged) return;
  }
}
