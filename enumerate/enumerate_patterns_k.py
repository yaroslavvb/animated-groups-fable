def compute():
    """The slow exact part: colour groups, based-seat orbits, per-type data.
    Cached in enumerate/out/ (delete the pickle to force recompute)."""
    print("colour groups (k <= %d) ..." % KMAX)
    groups = all_colour_groups()
    print("  %d classes (17 trivial + 269)" % len(groups))

    gsmap, ref2_sigs, _ = load_refs()

    strata = {hm: strata_of(hm) for hm in ORDER17}
    moves_cache = {hm: normaliser_moves(GROUPS[hm]) for hm in ORDER17}
    subs_cache = {}

    print("pattern-type orbits (based seats per colour group) ...")
    records = []
    for r in groups:
        hm, k, cid = r["hm"], r["k"], r["id"]
        G = GROUPS[hm]
        st = strata[hm]
        if (hm, k) not in subs_cache:
            subs_cache[(hm, k)] = ([full_group_sub(G)] if k == 1
                                   else subgroups_index_k(G, k))
        index = {s.key: s for s in subs_cache[(hm, k)]}

        # display subgroup: reference-matched for k=2 (SoT Table 11.1
        # signatures), canonical minimum otherwise
        H = index[min(sorted(r["orbit"]))]
        if k == 2:
            sym = gsmap.get(cid, {}).get("gs")
            want = None
            if sym is not None:
                want = ref2_sigs.get(
                    sym.replace("]", "]_") if not sym.endswith("]") else sym)
            if want is not None:
                for kk in sorted(r["orbit"]):
                    sub = index[kk]
                    perms2 = {name: (1 if sub.contains(el) else 2)
                              for name, el in CHAIM[hm]["gens"]}
                    if signature_string(hm, perms2) == want:
                        H = sub
                        break

        TH = translation_stabilizer(H)
        objs = based_objects(G, H, TH, st)
        sgens = stabilizer_generators(H, r["orbit"], index, moves_cache[hm])
        orbs = based_orbits(G, H, TH, st, sgens, objs)

        for orb in orbs:
            sources = set()
            for kk in orb:
                sources |= objs[kk]["strata"]
            slist = sorted(sources,
                           key=lambda i: (ORDER_KIND[st[i]["kind"]],
                                          st[i]["letters"]))
            rep_i = slist[0]
            rep = st[rep_i]
            # re-base so the seat is the stratum's own symbol: H_t = g^-1 H g
            # (S_rep ⊆ H_t since g(rep base) has stabiliser in H)
            gg = None
            for kk in sorted(orb):
                if rep_i in objs[kk]["witnesses"]:
                    gg = objs[kk]["witnesses"][rep_i]
                    break
            assert gg is not None, (cid, "no witness for representative")
            Ht = apply_move(H, mv_inv(gg)) if gg != IDMOVE else H
            assert sub_contains_set(Ht, rep["S"]), (cid, rep["label"])
            letters = set()
            for i in sources:
                letters.update(st[i]["letters"])
            pp, variety = base_pp(hm, rep["stype"], letters)
            reps_c = coset_reps(G, Ht, k)
            cycles = {name: perm_of(G, Ht, reps_c, el)
                      for name, el in CHAIM[hm]["gens"]}
            records.append({
                "hm": hm, "k": k, "colour_group": cid, "rep": rep,
                "sources": [st[i] for i in slist], "pp": pp,
                "variety": variety, "H": Ht, "reps": reps_c,
                "cycles": cycles,
            })
        r["display_H"] = H

    return groups, records


def main():
    build_chaim()
    for hm in ORDER17:
        for name, el in CHAIM[hm]["gens"]:
            assert in_group(GROUPS[hm], el), (hm, name)
        check_relations(hm)

    gsmap, ref2_sigs, ref3 = load_refs()

    if os.path.exists(CACHE):
        with open(CACHE, "rb") as f:
            groups, records = pickle.load(f)
        print("loaded cache %s (%d groups, %d type records)"
              % (CACHE, len(groups), len(records)))
    else:
        groups, records = compute()
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        with open(CACHE, "wb") as f:
            pickle.dump((groups, records), f)
        print("cached -> %s" % CACHE)

    per_k = {}
    for t in records:
        per_k[t["k"]] = per_k.get(t["k"], 0) + 1
    print("  types per k:", {k: per_k[k] for k in sorted(per_k)})
    assert per_k[1] == 52, per_k
    assert per_k[2] == 88, per_k

    notes = assign_labels(records, gsmap)
    for n in notes:
        print("  NOTE", n)

    # k=2 regression against the existing catalogue E ids
    old_path = os.path.join(DOCS, "data", "two-color-patterns.json")
    with open(old_path, encoding="utf-8") as f:
        old = json.load(f)
    old_ids = {t["id"] for t in old["types"]}
    new2 = {t["anchor"] for t in records if t["k"] == 2}
    assert new2 == old_ids, ("k=2 anchors changed",
                             sorted(old_ids - new2), sorted(new2 - old_ids))
    print("  k=2 regression: 88/88 anchors identical to "
          "two-color-patterns.json")

    check_against_catalog3(records, gsmap, ref3)

    # ---- assemble JSON
    wall = wallpaper_records()
    ordinal_of = lambda cid: int(cid.split("-")[-1])
    records.sort(key=lambda t: (t["k"], ORDER17.index(t["hm"]),
                                ordinal_of(t["colour_group"]),
                                ORDER_KIND[t["rep"]["kind"]], t["pp"],
                                t["variety"], t.get("star", 0),
                                t.get("suffix", "")))

    types_of = {}
    for t in records:
        types_of.setdefault(t["colour_group"], []).append(t["anchor"])

    out_groups = []
    for r in groups:
        cid = r["id"]
        if cid not in types_of:
            continue
        hm, k = r["hm"], r["k"]
        G = GROUPS[hm]
        H = r["display_H"]
        sub_orb = GROUPS[r["subType"]].orb
        sig = None
        cyc_disp = {}
        if k == 1:
            action, normal, cyclic = "C1", True, True
            kern_orb = sub_orb
            cyc_disp = {name: "1" for name, _ in CHAIM[hm]["gens"]}
        else:
            reps = coset_reps(G, H, k)
            gen_perms = [perm_of(G, H, reps, g) for g in G.full_gens]
            S = perm_group(gen_perms, k)
            action = action_label(S, k)
            normal = (len(S) == k)
            cyclic = normal and action == "C%d" % k
            kern = kernel_sub(G, H, reps, k)
            kern_orb = GROUPS[classify_concrete(as_concrete_group(kern))].orb
            cyc_disp = {name: cycle_string(perm_of(G, H, reps, el))
                        for name, el in CHAIM[hm]["gens"]}
            if k == 2:
                perms2 = {name: (1 if H.contains(el) else 2)
                          for name, el in CHAIM[hm]["gens"]}
                sig = signature_string(hm, perms2)
        gs_sym = gsmap.get(cid, {}).get("gs")
        gs_pretty = None
        if gs_sym:
            gs_pretty = (gs_sym if gs_sym.endswith("]")
                         else gs_sym[:gs_sym.index("]") + 1]
                         + subscript(gs_sym[gs_sym.index("]") + 1:]))
        out_groups.append({
            "id": cid, "k": k, "hm": hm, "orb": G.orb,
            "sub": {"hm": r["subType"], "orb": sub_orb},
            "kernel_orb": kern_orb,
            "action": action, "normal": normal, "cyclic": cyclic,
            "gs": gs_pretty,
            "chaim_type": chaim_type_string(G, k, sub_orb, kern_orb,
                                            normal, sig),
            "cycles": cyc_disp,
            "types": types_of[cid],
        })

    out_types = []
    for t in records:
        hm, k, cid = t["hm"], t["k"], t["colour_group"]
        G = GROUPS[hm]
        B = view_basis(hm, G.basis)
        rep = t["rep"]
        Ht = t["H"]
        seed = seat_point(G, rep)
        seedc = cart(B, seed)
        angle = 0.0
        if rep["stype"].startswith("d"):
            refl = [e for e in rep["S"] if mdet(e[0]) == -1]
            if rep["kind"] == "edge":
                el = refl[0]
            else:
                letter = rep["letters"][0]
                el = dict(CHAIM[hm]["gens"]).get(letter)
                if el is None or el not in rep["S"]:
                    el = refl[0]
            p0, dd = line_of(el)
            dc = cart(B, dd)
            angle = math.degrees(math.atan2(dc[1], dc[0]))
        equiv = [{"kind": s["kind"], "letters": s["letters"],
                  "label": s["label"]} for s in t["sources"]]
        if rep["kind"] == "interior":
            swords = []
        elif rep["kind"] == "corner":
            swords = rep["letters"]
        else:
            swords = [rep["letters"][0]]
        # the marked symbols fix the seat copy's colour A (cycle fixes 0) —
        # for k >= 3 they may still permute the other colours
        # (wrap-around corner partners are conjugate words, not letters)
        for L in swords:
            if L in t["cycles"]:
                assert t["cycles"][L][0] == 0, (t["anchor"], L,
                                                t["cycles"][L])
        mind = min_orbit_distance(G, seed)
        ops = []
        for M, v in G.ops.items():
            A = cart_matrix(B, M)
            ops.append({
                "m": [round(A[0][0], 6), round(A[0][1], 6),
                      round(A[1][0], 6), round(A[1][1], 6)],
                "t": [round(x, 6) for x in cart(B, v)],
                "c": (EC.coset_index(Ht, t["reps"], (M, v))
                      if k > 1 else 0),
            })
        t1p = perm_of(G, Ht, t["reps"], (I2, (F(1), F(0)))) if k > 1 \
            else (0,)
        t2p = perm_of(G, Ht, t["reps"], (I2, (F(0), F(1)))) if k > 1 \
            else (0,)
        out_types.append({
            "id": t["anchor"],
            "label": t["label"],
            "pp": t["pp"], "variety": t["variety"],
            "star": t.get("star", 0),
            "k": k, "hm": hm, "colour_group": cid,
            "primitive": rep["kind"] == "interior",
            "cycles": {name: cycle_string(p)
                       for name, p in t["cycles"].items()},
            "seat": {"kind": rep["kind"], "letters": rep["letters"],
                     "label": rep["label"], "stype": rep["stype"],
                     "order": rep.get("order"),
                     "point": [round(x, 6) for x in seedc],
                     "angle": round(angle, 6),
                     "stab_words": swords, "equivalent": equiv},
            "render": {"ops": ops, "seed": [round(x, 6) for x in seedc],
                       "min_dist": round(mind, 6),
                       "t1": list(t1p), "t2": list(t2p)},
        })

    counts_types = {}
    counts_groups = {}
    for t in out_types:
        counts_types[str(t["k"])] = counts_types.get(str(t["k"]), 0) + 1
    for g in out_groups:
        counts_groups[str(g["k"])] = counts_groups.get(str(g["k"]), 0) + 1
    meta = {
        "title": "Patterns",
        "kmax": KMAX,
        "groups": counts_groups,
        "types": counts_types,
        "total_groups": len(out_groups),
        "total_types": len(out_types),
        "note": "Perfect periodic k-colour pattern types, k <= %d, as marked "
                "coloured orbifolds: colour group (catalogue D id) + based "
                "seat of the motif, up to affine equivalence.  Anchors: G&S "
                "Table 8.2.1 (colour-group counts), the 88 two-colour types "
                "of Figs 8.2.2/8.3.5, the 59 three-colour types of Figs "
                "8.2.3/8.3.6.  Labels for k >= 4 are systematic extensions "
                "(no published tables exist)." % KMAX,
    }
    path = os.path.join(DOCS, "data", "patterns.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"meta": meta, "wallpaper": wall, "groups": out_groups,
                   "types": out_types}, f, ensure_ascii=False, indent=1)
    print("wrote %s  (%d groups, %d types)" % (path, len(out_groups),
                                               len(out_types)))
    print("  groups per k:", counts_groups)
    print("  types  per k:", counts_types)


if __name__ == "__main__":
    main()
