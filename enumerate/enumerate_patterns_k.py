def chaim_type_string(G, k, sub_orb, kern_orb, normal, sig):
    if k == 1:
        return G.orb
    if k == 2:
        tag = ""
        if G.hm == "pm" and sub_orb == "**":
            tag = {"²*¹*¹": " (1)", "¹*¹*²": " (2)"}.get(sig, "")
        return "%s/%s%s" % (G.orb, sub_orb, tag)
    sup = {2: "²", 3: "³", 4: "⁴", 5: "⁵", 6: "⁶"}[k]
    if normal:
        return "%s%s/%s" % (G.orb, sup, sub_orb)
    return "%s%s//%s" % (G.orb, sup, kern_orb)


def wallpaper_records():
    wall = {}
    for hm in ORDER17:
        G = GROUPS[hm]
        B = view_basis(hm, G.basis)
        gens = []
        for name, el in CHAIM[hm]["gens"]:
            M, v = el
            entry = {"name": name, "geometry": CHAIM[hm]["geometry"][name]}
            if M == I2:
                entry["kind"] = "translation"
                entry["vector"] = list(cart(B, v))
            elif mdet(M) == 1:
                c = EP.rotation_centre(el)
                entry["kind"] = "rotation"
                entry["centre"] = list(cart(B, c))
                entry["order"] = EP.rotation_order(M)
                A = cart_matrix(B, M)
                entry["angle_degrees"] = round(
                    math.degrees(math.atan2(A[1][0], A[0][0])), 6)
            else:
                if EP.is_reflection(el):
                    p0, d = line_of(el)
                    entry["kind"] = "mirror"
                    entry["axis_point"] = list(cart(B, p0))
                    dc = cart(B, d)
                    nrm = math.hypot(*dc)
                    entry["axis_direction"] = [dc[0] / nrm, dc[1] / nrm]
                    entry["glide"] = 0.0
                else:
                    IM = ((1 - M[0][0], -M[0][1]), (-M[1][0], 1 - M[1][1]))
                    if IM[0] != (0, 0):
                        d = (-IM[0][1], IM[0][0])
                    else:
                        d = (-IM[1][1], IM[1][0])
                    dc = cart(B, d)
                    nrm = math.hypot(*dc)
                    dc = (dc[0] / nrm, dc[1] / nrm)
                    vc = cart(B, v)
                    along = vc[0] * dc[0] + vc[1] * dc[1]
                    perp = (vc[0] - along * dc[0], vc[1] - along * dc[1])
                    entry["kind"] = "glide"
                    entry["axis_point"] = [perp[0] / 2, perp[1] / 2]
                    entry["axis_direction"] = list(dc)
                    entry["glide"] = along
            gens.append(entry)
        wall[hm] = {"hm": hm, "orbifold": G.orb, "summary": SUMMARY[hm],
                    "basis": [[B[0][0], B[0][1]], [B[1][0], B[1][1]]],
                    "annotated": CHAIM[hm]["annotated"],
                    "template": CHAIM[hm]["template"],
                    "relations": CHAIM[hm]["relations"],
                    "generators": gens}
    return wall


