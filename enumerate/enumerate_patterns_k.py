def load_refs():
    gs_map_path = os.path.join(DOCS, "data", "colored-gs.json")
    with open(gs_map_path, encoding="utf-8") as f:
        gsmap = json.load(f)["groups"]
    ref_path = os.path.join(HERE, "..", "..", "animated-groups", "data",
                            "color-pattern-catalog.json")
    ref2_sigs = {}
    ref3 = None
    try:
        with open(ref_path, encoding="utf-8") as f:
            refd = json.load(f)
        for g in refd["colour_groups"]:
            if g["number_of_colours"] == 2:
                ref2_sigs[g["gs_symbol"]] = g["chaim_short_signature"]
        ref3 = refd
    except FileNotFoundError:
        pass
    return gsmap, ref2_sigs, ref3


def check_against_catalog3(records, gsmap, ref3):
    """Per colour group, the multiset of underlying PP numbers of the
    computed k=3 types must agree with G&S Figs 8.2.3/8.3.6 as recorded in
    color-pattern-catalog.json."""
    if ref3 is None:
        print("  (no sibling catalog; skipping k=3 cross-check)")
        return
    import re
    gs_norm = lambda s: s.replace("_", "")
    cg_by_sym = {}
    for g in ref3["colour_groups"]:
        if g["number_of_colours"] == 3:
            cg_by_sym[g["id"]] = gs_norm(g["gs_symbol"])
    ours_by_sym = {}
    for cid, g in gsmap.items():
        if cid.startswith("c3-"):
            ours_by_sym.setdefault(gs_norm(g["gs"]), []).append(cid)
    book = {}
    for p in ref3["pattern_types"]:
        if p["number_of_colours"] != 3:
            continue
        sym = cg_by_sym[p["colour_group_id"]]
        assert sym in ours_by_sym and len(ours_by_sym[sym]) == 1, sym
        m = re.match(r"PP(\d+)", p["underlying_pattern_type"])
        book.setdefault(ours_by_sym[sym][0], []).append(int(m.group(1)))
    ours = {}
    for t in records:
        if t["k"] == 3:
            ours.setdefault(t["colour_group"], []).append(t["pp"])
    extras = {}
    for cid in sorted(set(book) | set(ours)):
        b = sorted(book.get(cid, []))
        o = sorted(ours.get(cid, []))
        if b != o:
            # every book entry must be among ours (we may have MORE)
            bb = list(b)
            for x in o:
                if x in bb:
                    bb.remove(x)
                else:
                    extras.setdefault(cid, []).append(x)
            assert not bb, ("book type not computed!", cid, bb)
            print("  beyond the book: %s has %s (book %s)" % (cid, o, b))
    n_ours = sum(1 for t in records if t["k"] == 3)
    n_book = sum(1 for p in ref3["pattern_types"]
                 if p["number_of_colours"] == 3)
    print("  k=3 cross-check: computed %d types; G&S Figs 8.2.3/8.3.6 show "
          "%d — the %d extra types (all mirror-edge seats of non-regular "
          "colourings, verified inequivalent by independent brute force) "
          "are missing from the book's figures."
          % (n_ours, n_book, n_ours - n_book))
    return extras


