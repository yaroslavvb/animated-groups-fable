def recentre(q, TH):
    """Shift q by a T_H vector to bring it near the origin (T_H-conjugation
    fixes H and the colour classes, so this is a free renderer choice)."""
    t1, t2 = lat_cols(TH)
    best = None
    for i in range(-3, 4):
        for j in range(-3, 4):
            c = (q[0] + i * t1[0] + j * t2[0], q[1] + i * t1[1] + j * t2[1])
            d = float(c[0]) ** 2 + float(c[1]) ** 2
            if best is None or d < best[0]:
                best = (d, c)
    return best[1]


