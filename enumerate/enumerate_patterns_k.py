"""k-colour pattern types of the plane, k <= 6: exact enumeration.

Generalises enumerate_patterns.py (the two-colour case, Grünbaum & Shephard's
88) to every perfect k-colouring with k <= 6.  A k-coloured pattern type is a
chain  S <= H <= Gamma  — S the full site symmetry of the motif's seat, H the
stabiliser of one colour (index k; the colour group is the pair Gamma > H of
catalogue D) — up to simultaneous conjugation by the affine normaliser
N(Gamma).  The admissibility condition is S ⊆ H: every symmetry fixing the
marked copy fixes its colour.

For k = 2 the subgroup H is normal, so the chain is determined by the
Gamma-orbit of the seat (the *stratum*) together with H, which is how
enumerate_patterns.py computes the 88.  For k >= 3 the subgroup need not be
normal and S ⊆ H depends on which point of the stratum carries the marked
copy: the correct datum is a *based* chain (seat point, H).  This module
therefore enumerates, per colour-group class with representative H:

  * the admissible based seats — all Gamma-images of each symbolic stratum's
    base point (reduced modulo T_H, the lattice of translations normalising
    H) whose full stabiliser lies in H; for segment-free mirror edges the
    based datum is the conjugated reflection itself;
  * orbits of these under Stab_{N(Gamma)}(H), generated by Schreier
    generators obtained from a transversal of the subgroup-key orbit.

Each orbit is one pattern type.  For display, a representative is re-based so
the seat is a *literal* symbol of the annotated signature (a letter's own
mirror or centre), conjugating H accordingly within its class — so the red
seat mark always sits on colour-preserving symbols.

Anchors:
  k=1  ->  52 marked strata = the 51 uncoloured pattern types PP1..PP51
           (PP48 splits into varieties A and B);
  k=2  ->  88 types, anchors regression-checked against
           docs/data/two-color-patterns.json;
  k=3  ->  compared against the 59 three-colour types of G&S Figures
           8.2.3/8.3.6 via the sibling repo's color-pattern-catalog.json;
  k>=4 ->  no published pattern-type tables exist; labels are systematic
           extensions PPn[k] with the colour-group ordinal of catalogue D.

Colour bookkeeping: colours are the left cosets of the pane's subgroup H,
labelled A.. in the BFS order of coset_reps; the colour permutation of g is
sigma_g(i) = index of g·r_i, so translations act on a rendered copy's colour
by sigma_{e1}^i · sigma_{e2}^j — the renderer needs only the base colour of
each of the |P| coset ops and the two translation permutations.

Emits docs/data/patterns.json.  Run:  python3 enumerate_patterns_k.py
"""

