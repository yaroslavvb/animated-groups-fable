def base_pp(hm, stype, letters):
    """Underlying uncoloured pattern number and variety letter."""
    n = PP_TABLE[hm][stype]
    suffix = ""
    if hm == "p4m" and stype == "d1":
        n = 39 if "Q" in letters else 38
    if hm == "p6m" and stype == "d1":
        if "P" in letters:
            n = 47
        elif "Q" in letters:
            n, suffix = 48, "A"
        else:
            n, suffix = 48, "B"
    return n, suffix


def star_rule(hm, rep, cycles):
    """The G&S star for pmm PP15-style splits: '' when the seat mirror is
    adjacent (perpendicular) to a colour-moving mirror, '*' when parallel."""
    if rep["kind"] != "edge":
        return None
    moving = {name for name, p in cycles.items()
              if p != tuple(range(len(p)))}
    order = [name for name, _ in CHAIM[hm]["gens"]]
    L = rep["letters"][0]
    if L not in order:
        return None
    i = order.index(L)
    nleft = order[(i - 1) % len(order)]
    nright = order[(i + 1) % len(order)]
    adjacent = (nleft in moving) or (nright in moving)
    return "" if adjacent else "*"


ORDER_KIND = {"interior": 0, "edge": 1, "corner": 2, "gyration": 3}


def line_word(hm, rep, Ht, reps_c, k, n_copies=12):
    """Colour word of the copies along an edge seat's mirror line, starting
    at the seat and walking in the +direction; classifies the variant.
    Returns (word, cls) with cls in {'const', 'single', 'doubled'}."""
    if rep["kind"] != "edge" or rep.get("line") is None:
        return None, None
    G = GROUPS[hm]
    p0, dvec = rep["line"]
    seed = rep["point"]
    if seed is None:
        # segment-free edge: the seat is anywhere on the line
        seed = p0
    hits = {}
    for M, v in G.ops.items():
        for nx in range(-8, 9):
            for ny in range(-8, 9):
                g = (M, vadd(v, (F(nx), F(ny))))
                q = vadd(mvec(M, rep["point"] if rep["point"] is not None
                              else p0), g[1])
                w = vsub(q, seed)
                if w[0] * dvec[1] - w[1] * dvec[0] != 0:
                    continue
                s = (w[0] / dvec[0]) if dvec[0] else (w[1] / dvec[1])
                if s < 0 or s in hits:
                    continue
                hits[s] = EC.coset_index(Ht, reps_c, g)
    word = "".join(LETTERS[hits[s]] for s in sorted(hits)[:n_copies])
    if len(set(word)) == 1:
        cls = "const"
    elif any(word[i] == word[i + 1] for i in range(len(word) - 1)):
        cls = "doubled"
    else:
        cls = "single"
    return word, cls


# Star order for the k=3 buckets that outgrow the book's figures, matched to
# the printed panels of Figs 8.2.3/8.3.6 by the seat-line colour word (the
# panels' variants were identified visually; see the session notes).  Types
# beyond the list order (or beyond the book's count) get extra stars.
K3_STAR_ORDER = {
    ("c3-pmm-1", 15): [("P", "single"), ("Q", "const"), ("P", "doubled")],
    ("c3-cmm-1", 19): [("P", "const"), ("Q", "single"), ("Q", "doubled")],
    ("c3-p3m1-2", 28): [("P", "const"), ("Q", "const")],
    ("c3-p6m-2", 47): [("P", "single"), ("P", "doubled"), ("P", "doubled")],
}


def assign_labels(records, gsmap):
    """Attach pretty label + anchor id per type record (in place)."""
    by_group = {}
    for t in records:
        by_group.setdefault(t["colour_group"], []).append(t)
    notes = []
    for cid, recs in by_group.items():
        hm, k = recs[0]["hm"], recs[0]["k"]
        recs.sort(key=lambda t: (ORDER_KIND[t["rep"]["kind"]], t["pp"],
                                 t["variety"], t["rep"]["letters"]))
        ordinal = int(cid.split("-")[-1])
        gs_sym = gsmap.get(cid, {}).get("gs")
        gsub = ""
        if gs_sym and not gs_sym.endswith("]"):
            gsub = gs_sym[gs_sym.index("]") + 1:]
        buckets = {}
        for t in recs:
            buckets.setdefault((t["pp"], t["variety"]), []).append(t)
        for (pp, variety), ts in buckets.items():
            if len(ts) == 1:
                ts[0]["star"], ts[0]["suffix"] = 0, ""
            elif k == 3 and (cid, pp) in K3_STAR_ORDER:
                order_spec = K3_STAR_ORDER[(cid, pp)]
                keyed = []
                for t in ts:
                    word, cls = line_word(hm, t["rep"], t["H"], t["reps"], k)
                    keyed.append((t, (t["rep"]["letters"][0], cls), word))
                assert sorted(x[1] for x in keyed) == sorted(order_spec), (
                    cid, pp, [x[1] for x in keyed], order_spec)
                # order by the spec, ties broken by the colour word
                pos = {}
                ordered = []
                for spec in order_spec:
                    cands = sorted((x for x in keyed
                                    if x[1] == spec and id(x[0]) not in pos),
                                   key=lambda x: x[2])
                    x = cands[0]
                    pos[id(x[0])] = True
                    ordered.append(x[0])
                for i, t in enumerate(ordered):
                    t["star"], t["suffix"] = i, ""
                ts[:] = ordered
                notes.append("%s PP%d%s[3]: %d variants ordered to the "
                             "printed panels (seat-line words %s)"
                             % (cid, pp, variety, len(ts),
                                [x[2][:6] for x in keyed]))
            elif len(ts) == 2 and k <= 3:
                stars = [star_rule(hm, t["rep"], t["cycles"]) for t in ts]
                if sorted(x for x in stars if x is not None) == ["", "*"]:
                    for t, s in zip(ts, stars):
                        t["star"], t["suffix"] = (1 if s == "*" else 0), ""
                else:
                    ts[0]["star"], ts[1]["star"] = 0, 1
                    ts[0]["suffix"] = ts[1]["suffix"] = ""
                    notes.append("%s PP%d%s[%d]: star assigned by order, "
                                 "verify against the plates"
                                 % (cid, pp, variety, k))
                ts.sort(key=lambda t: t["star"])
            elif k == 3:
                for i, t in enumerate(ts):
                    t["star"], t["suffix"] = i, ""
                notes.append("%s PP%d%s[3]: %d variants (book shows fewer); "
                             "stars by canonical order"
                             % (cid, pp, variety, len(ts)))
            else:
                # tie-break on a canonical content fingerprint (the cycle
                # structure), never on residual list order
                ts.sort(key=lambda t: [cycle_string(t["cycles"][name])
                                       for name, _ in CHAIM[hm]["gens"]])
                for i, t in enumerate(ts):
                    t["star"], t["suffix"] = 0, "abcdef"[i]
        for t in recs:
            pp, variety = t["pp"], t["variety"]
            star = "*" * t.get("star", 0)
            suff = t.get("suffix", "")
            if k == 1:
                t["label"] = "PP%d%s" % (pp, variety)
                t["anchor"] = "pp%d%s" % (pp, variety.lower())
            elif k <= 3 and gs_sym:
                t["label"] = "PP%d%s[%d]%s%s%s" % (
                    pp, variety, k, subscript(gsub) if gsub else "", star,
                    suff)
                t["anchor"] = "pp%d%s-%d" % (pp, variety.lower(), k)
                if gsub:
                    t["anchor"] += "-" + gsub
                t["anchor"] += "s" * t.get("star", 0)
                if suff:
                    t["anchor"] += suff
            else:
                t["label"] = "PP%d%s[%d]%s%s%s" % (
                    pp, variety, k, subscript(ordinal), star, suff)
                t["anchor"] = "pp%d%s-%d-o%d%s%s" % (
                    pp, variety.lower(), k, ordinal, "s" * t.get("star", 0),
                    suff)
    anchors = [t["anchor"] for t in records]
    assert len(anchors) == len(set(anchors)), "duplicate anchors"
    return notes


