def full_group_sub(G):
    """H = Gamma itself as a Sub (the trivial 1-colouring)."""
    w = {M: v for M, v in G.ops.items()}
    return Sub(((1, 0), (0, 1)), w.keys(), w)


def all_colour_groups():
    """Colour-group classes for k = 1..KMAX with catalogue-D ids (the sort of
    enumerate_colored.main, so c{k}-{hm}-{n} match colored.json)."""
    results = EC.enumerate_all(kmax=KMAX, verbose=False)
    for r in results:
        r["subType"] = classify_concrete(as_concrete_group(r["sub"]))
    results.sort(key=lambda r: (r["k"], ORDER17.index(r["hm"]),
                                ORDER17.index(r["subType"]),
                                lat_index(r["sub"].L), str(r["sub"].key)))
    counters = {}
    for r in results:
        c = counters.setdefault((r["k"], r["hm"]), [0])
        c[0] += 1
        r["id"] = "c%d-%s-%d" % (r["k"], r["hm"], c[0])
    for hm in ORDER17:
        for k in range(2, KMAX + 1):
            n = sum(1 for r in results if r["hm"] == hm and r["k"] == k)
            assert n == TABLE_8_2_1[hm][k - 2], (hm, k, n)
    trivial = []
    for hm in ORDER17:
        G = GROUPS[hm]
        sub = full_group_sub(G)
        trivial.append({"hm": hm, "k": 1, "sub": sub,
                        "orbit": frozenset({sub.key}),
                        "properClasses": 1, "subType": hm,
                        "id": "c1-%s-1" % hm})
    return trivial + results


# ------------------------------------------------------- based-seat machinery

def translation_stabilizer(H):
    """HNF of T_H = { n in Z^2 : (I|n) H (I|n)^{-1} = H }; contains H ∩ T."""
    gens = [tuple(int(x) for x in v) for v in lat_cols(H.L)]
    for n in lat_box(H.L):
        if n == (F(0), F(0)):
            continue
        if apply_move(H, (I2, n)).key == H.key:
            gens.append((int(n[0]), int(n[1])))
    TH = hnf_of(gens)
    assert apply_move(H, (I2, (F(TH[0][0]), F(0)))).key == H.key
    return TH


def conj_el(g, el):
    return gmul(gmul(g, el), ginv(g))


def edge_line_key(el, TH):
    """Canonical key of a reflection's mirror line modulo conjugation by
    translations in T_H (cf. enumerate_patterns.canon_line, which reduces
    modulo all of Gamma and Z^2)."""
    M, w = el
    IM = ((1 - M[0][0], -M[0][1]), (-M[1][0], 1 - M[1][1]))
    g1 = (IM[0][0], IM[1][0])
    g2 = (IM[0][1], IM[1][1])
    u0 = g1 if g1 != (0, 0) else g2
    gg = math.gcd(abs(u0[0]), abs(u0[1]))
    u0 = (u0[0] // gg, u0[1] // gg)
    # w is parallel to u0 for a reflection
    lam = (F(w[0]) / u0[0]) if u0[0] else (F(w[1]) / u0[1])
    assert vsub(w, (lam * u0[0], lam * u0[1])) == ZERO, ("not a reflection", el)
    # (I - M) T_H = step * u0 * Z
    t1, t2 = lat_cols(TH)
    steps = []
    for t in (t1, t2):
        im = mvec(IM, t)
        if im == (0, 0):
            continue
        c = (F(im[0]) / u0[0]) if u0[0] else (F(im[1]) / u0[1])
        assert c.denominator == 1
        steps.append(abs(int(c)))
    step = 0
    for s in steps:
        step = math.gcd(step, s)
    assert step > 0, ("degenerate edge lattice", el, TH)
    return ("ln", M, lam % step)


def based_objects(G, H, TH, strata_list):
    """All admissible based seats for the subgroup H, as
    key -> {"strata": set of stratum indices, "datum": exact datum,
            "witness": (stratum index, g) with datum = image of the
            stratum's own base under g}."""
    box = lat_box(TH)
    out = {}

    def add(key, i, datum, g):
        rec = out.setdefault(key, {"strata": set(), "datum": datum,
                                   "witnesses": {}})
        rec["strata"].add(i)
        rec["witnesses"].setdefault(i, g)

    for i, s in enumerate(strata_list):
        if s["kind"] == "interior":
            add(("int",), i, None, IDMOVE)
            continue
        if s["point"] is not None:
            p = s["point"]
            for M, v in G.ops.items():
                for n in box:
                    g = (M, vadd(v, n))
                    q = vadd(mvec(M, p), g[1])
                    qr = wred(q, TH)
                    S = stabiliser(G, qr)
                    if not sub_contains_set(H, S):
                        continue
                    # witness with the exact reduction translation folded in
                    shift = vsub(qr, q)
                    gw = mv_compose((I2, shift), g)
                    add(("pt", qr), i, qr, gw)
        else:
            el = [e for e in s["S"] if e[0] != I2][0]
            for M, v in G.ops.items():
                for n in box:
                    g = (M, vadd(v, n))
                    el2 = conj_el(g, el)
                    if not H.contains(el2):
                        continue
                    add(edge_line_key(el2, TH), i, el2, g)
    return out


def stabilizer_generators(H, orbit_keys, index, moves):
    """Schreier generators of Stab_{N(Gamma)}(H) from the move action on the
    subgroup-key orbit, as affine maps (A | t).  Schreier's lemma needs the
    generating set closed under inverses."""
    moves = list({mv: True for mv in
                  list(moves) + [mv_inv(mv) for mv in moves]})
    trans = {H.key: IDMOVE}
    frontier = [H.key]
    while frontier:
        nxt = []
        for x in frontier:
            for mv in moves:
                y = apply_move(index[x], mv).key
                if y not in trans:
                    trans[y] = mv_compose(mv, trans[x])
                    nxt.append(y)
        frontier = nxt
    assert set(trans) == set(orbit_keys), "transversal misses orbit keys"
    sgens = {}
    for x, ux in trans.items():
        for mv in moves:
            y = apply_move(index[x], mv).key
            s = mv_compose(mv_inv(trans[y]), mv_compose(mv, ux))
            if s != IDMOVE:
                sgens[s] = True
    for s in sgens:
        assert apply_move(H, s).key == H.key, ("Schreier gen moves H", s)
    return list(sgens)


def based_orbits(G, H, TH, strata_list, sgens, objs):
    """Partition the admissible based seats into Stab(H)-orbits."""

    def act(key, mv):
        A, t = mv
        if key[0] == "int":
            return ("int",)
        if key[0] == "pt":
            q = vadd(mvec(A, key[1]), t)
            return ("pt", wred(q, TH))
        el = objs[key]["datum"]
        M, v = el
        Ai = minv_uni(A)
        Mp = mmul(mmul(A, M), Ai)
        wp = vsub(vadd(t, mvec(A, v)), mvec(Mp, t))
        return edge_line_key((Mp, wp), TH)

    # iterate in dict insertion order: deterministic across processes
    # (set.pop() order is hash-randomised and leaked into label suffixes)
    seen = set()
    orbits_ = []
    for k0 in objs:
        if k0 in seen:
            continue
        orb = {k0}
        frontier = [k0]
        while frontier:
            nxt = []
            for kk in frontier:
                for mv in sgens:
                    k2 = act(kk, mv)
                    assert k2 in objs, (G.hm, "based seat moved outside")
                    if k2 not in orb:
                        orb.add(k2)
                        nxt.append(k2)
            frontier = nxt
        seen |= orb
        orbits_.append(orb)
    return orbits_


