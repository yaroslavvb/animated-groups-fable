def subscript(s):
    return "".join(SUBSCRIPT[ch] for ch in str(s))


def cycle_string(perm):
    """'(AB)(CD)' / '(ABC)' / '1' from an image tuple."""
    n = len(perm)
    seen = [False] * n
    out = []
    for i in range(n):
        if seen[i] or perm[i] == i:
            seen[i] = True
            continue
        cyc = [i]
        seen[i] = True
        j = perm[i]
        while j != i:
            cyc.append(j)
            seen[j] = True
            j = perm[j]
        out.append("(" + "".join(LETTERS[c] for c in cyc) + ")")
    return "".join(out) if out else "1"


# ---------------------------------------------------------- affine map words

def mv_compose(a, b):
    """(A1|t1) ∘ (A2|t2) = (A1 A2 | A1 t2 + t1)."""
    (A1, t1), (A2, t2) = a, b
    return (mmul(A1, A2), vadd(mvec(A1, t2), t1))


def mv_inv(a):
    A, t = a
    Ai = minv_uni(A)
    w = mvec(Ai, t)
    return (Ai, (-w[0], -w[1]))


