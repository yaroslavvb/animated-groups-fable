def mmul_frac(A, B):
    return (
        (F(A[0][0]) * B[0][0] + F(A[0][1]) * B[1][0],
         F(A[0][0]) * B[0][1] + F(A[0][1]) * B[1][1]),
        (F(A[1][0]) * B[0][0] + F(A[1][1]) * B[1][0],
         F(A[1][0]) * B[0][1] + F(A[1][1]) * B[1][1]),
    )


def as_concrete_group(sub):
    """Express H (a subgroup datum) as a wallpaper group in its own primitive
    coordinates: point dict M' -> v' (mod 1) with T = Z^2."""
    Lcols = lat_cols(sub.L)
    Bmat = ((Lcols[0][0], Lcols[1][0]), (Lcols[0][1], Lcols[1][1]))
    d = mdet(Bmat)
    Bi = ((F(Bmat[1][1], d), F(-Bmat[0][1], d)),
          (F(-Bmat[1][0], d), F(Bmat[0][0], d)))
    ops = {}
    for M, w in sub.w.items():
        Mp = mmul_frac(Bi, mmul_frac(M, Bmat))
        for row in Mp:
            for x in row:
                assert is_int(x), ("H point matrix not integral in L-basis", M)
        Mp = ((int(Mp[0][0]), int(Mp[0][1])), (int(Mp[1][0]), int(Mp[1][1])))
        ops[Mp] = vmod1(mvec(Bi, w))
    return ops


