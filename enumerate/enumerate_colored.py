# ---------------------------------------------------------------- basic 2x2

def mmul(A, B):
    return (
        (A[0][0] * B[0][0] + A[0][1] * B[1][0], A[0][0] * B[0][1] + A[0][1] * B[1][1]),
        (A[1][0] * B[0][0] + A[1][1] * B[1][0], A[1][0] * B[0][1] + A[1][1] * B[1][1]),
    )


def mvec(A, v):
    return (A[0][0] * v[0] + A[0][1] * v[1], A[1][0] * v[0] + A[1][1] * v[1])


def mdet(A):
    return A[0][0] * A[1][1] - A[0][1] * A[1][0]


def minv_uni(A):
    """Inverse of a unimodular integer matrix (det = +-1)."""
    d = mdet(A)
    assert d in (1, -1), A
    return ((d * A[1][1], -d * A[0][1]), (-d * A[1][0], d * A[0][0]))


def vadd(u, v):
    return (u[0] + v[0], u[1] + v[1])


def vsub(u, v):
    return (u[0] - v[0], u[1] - v[1])


def is_int(x):
    return F(x).denominator == 1


def vmod1(v):
    return (F(v[0]) % 1, F(v[1]) % 1)


# ------------------------------------------------- group elements (M | v)

def gmul(a, b):
    """(M|v) (N|w) = (MN | v + M w).  Exact, no reduction."""
    (M, v), (N, w) = a, b
    return (mmul(M, N), vadd(v, mvec(M, w)))


def ginv(a):
    M, v = a
    Mi = minv_uni(M)
    w = mvec(Mi, v)
    return (Mi, (-w[0], -w[1]))


def point_group_from_gens(gens):
    """Close {(M | v mod 1)} under multiplication: the finite quotient
    Gamma/T as a dict M -> v (each matrix once, translation part mod 1)."""
    ops = {I2: ZERO}
    changed = True
    while changed:
        changed = False
        items = list(ops.items())
        for M1, v1 in items:
            for M2, v2 in list(gens) + items:
                M, v = gmul((M1, v1), (M2, v2))
                v = vmod1(v)
                if M not in ops:
                    ops[M] = v
                    changed = True
                else:
                    d = vsub(ops[M], v)
                    assert is_int(d[0]) and is_int(d[1]), \
                        "inconsistent translation parts in point-group closure"
    return ops


