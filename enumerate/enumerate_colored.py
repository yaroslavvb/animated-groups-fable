# --------------------------------------------------------------- sublattices

def divisors(n):
    return [d for d in range(1, n + 1) if n % d == 0]


def sublattices(a):
    """All sublattices of Z^2 of index a, as HNF matrices ((d1, c), (0, d2)):
    columns b1 = (d1, 0), b2 = (c, d2), with d1*d2 = a, 0 <= c < d1."""
    out = []
    for d1 in divisors(a):
        d2 = a // d1
        for c in range(d1):
            out.append(((d1, c), (0, d2)))
    return out


def in_lat(v, B):
    """Is the rational vector v in the lattice with HNF matrix B?"""
    d1, c = B[0]
    d2 = B[1][1]
    j = F(v[1]) / d2
    if j.denominator != 1:
        return False
    i = (F(v[0]) - c * j) / d1
    return i.denominator == 1


def lat_cols(B):
    return ((B[0][0], B[1][0]), (B[0][1], B[1][1]))   # b1, b2


def lat_index(B):
    return B[0][0] * B[1][1]


def hnf_of(vectors):
    """HNF ((d1,c),(0,d2)) of the lattice generated by integer vectors
    (must have rank 2)."""
    vs = [(int(v[0]), int(v[1])) for v in vectors if v != (0, 0)]
    # euclidean reduction on the second coordinate
    while True:
        nz = [v for v in vs if v[1] != 0]
        if len(nz) <= 1:
            break
        piv = min(nz, key=lambda v: abs(v[1]))
        out = []
        for v in vs:
            if v is piv or v[1] == 0:
                if v is not piv:
                    out.append(v)
                continue
            q = v[1] // piv[1]
            out.append((v[0] - q * piv[0], v[1] - q * piv[1]))
        vs = out + [piv]
    piv = [v for v in vs if v[1] != 0]
    assert piv, ("rank < 2", vectors)
    piv = piv[0]
    if piv[1] < 0:
        piv = (-piv[0], -piv[1])
    xs = [abs(v[0]) for v in vs if v[1] == 0 and v[0] != 0]
    assert xs, ("rank < 2", vectors)
    d1 = 0
    for x in xs:
        d1 = math.gcd(d1, x)
    d2 = piv[1]
    c = piv[0] % d1
    return ((d1, c), (0, d2))


def wred(w, B):
    """Canonical representative of the rational vector w modulo the lattice B:
    fractional parts kept, integer part reduced into the HNF box."""
    fx, fy = F(w[0]) % 1, F(w[1]) % 1
    nx, ny = int(w[0] - fx), int(w[1] - fy)
    d1, c = B[0]
    d2 = B[1][1]
    j = ny // d2
    nx, ny = nx - j * c, ny - j * d2
    i = nx // d1
    nx = nx - i * d1
    return (nx + fx, ny + fy)


def lat_box(B):
    """Coset representatives of Z^2 / B."""
    d1 = B[0][0]
    d2 = B[1][1]
    return [(F(i), F(j)) for i in range(d1) for j in range(d2)]


# ------------------------------------------------ exact congruence solving

def solve_cong(pairs):
    """Solve the system  IM_r · t ≡ rhs_r (mod Z^2), r = 1..m,  for t in Q^2.
    pairs = [(IM, rhs)] with IM integer 2x2, rhs rational 2-vector.
    Returns a particular rational solution t, or None if unsolvable.
    (Continuous solution directions exist when the stacked matrix has rank
    < 2; they are irrelevant for existence and a rational particular
    solution is always produced when solvable.)"""
    R = []
    r = []
    for IM, rhs in pairs:
        R.append([IM[0][0], IM[0][1]])
        R.append([IM[1][0], IM[1][1]])
        r.append(F(rhs[0]))
        r.append(F(rhs[1]))
    m = len(R)
    if m == 0:
        return ZERO
    D, U, V = smith_normal_form([row[:] for row in R])
    Ur = [sum(F(U[i][j]) * r[j] for j in range(m)) for i in range(m)]
    s = [F(0), F(0)]
    for i in range(m):
        d = D[i][0] if i == 0 else (D[i][1] if i == 1 else 0)
        if i < 2 and d != 0:
            s[i] = Ur[i] / d
        else:
            if not is_int(Ur[i]):
                return None
    t = (F(V[0][0]) * s[0] + F(V[0][1]) * s[1],
         F(V[1][0]) * s[0] + F(V[1][1]) * s[1])
    return t


def conj_pairs(G, A, target_ops):
    """The congruence system for (A|t) to conjugate G onto target_ops.
    Returns None if the matrix parts do not match."""
    Ai = minv_uni(A)
    pairs = []
    for M, v in G.items():
        Mp = mmul(mmul(A, M), Ai)
        if Mp not in target_ops:
            return None
        IM = ((1 - Mp[0][0], -Mp[0][1]), (-Mp[1][0], 1 - Mp[1][1]))
        rhs = vsub(target_ops[Mp], mvec(A, v))
        pairs.append((IM, rhs))
    return pairs


# ------------------------------------------------------- subgroup enumeration

def point_subgroups(P):
    """All subgroups of the finite matrix group P (<= 12 elements; all 2D
    point groups are generated by at most 2 elements)."""
    mats = list(P)
    found = {}

    def close(gens):
        S = {I2}
        frontier = [I2]
        while frontier:
            nxt = []
            for A in frontier:
                for g in gens:
                    Bm = mmul(g, A)
                    if Bm not in S:
                        S.add(Bm)
                        nxt.append(Bm)
            frontier = nxt
        return tuple(sorted(S))

    found[close([])] = True
    for g1 in mats:
        found[close([g1])] = True
        for g2 in mats:
            found[close([g1, g2])] = True
    return list(found.keys())


def min_gens(Q):
    """A minimal generating list for the subgroup Q (tuple of matrices)."""
    Qset = set(Q)
    if Qset == {I2}:
        return []

    def close(gens):
        S = {I2}
        frontier = [I2]
        while frontier:
            nxt = []
            for A in frontier:
                for g in gens:
                    Bm = mmul(g, A)
                    if Bm not in S:
                        S.add(Bm)
                        nxt.append(Bm)
            frontier = nxt
        return S

    for g in Q:
        if close([g]) == Qset:
            return [g]
    for g1, g2 in itertools.combinations([m for m in Q if m != I2], 2):
        if close([g1, g2]) == Qset:
            return [g1, g2]
    raise AssertionError("point subgroup needs > 2 generators")


class Sub:
    """A subgroup H < Gamma of finite index: H = { (M | w_M + L) : M in Q }."""

    __slots__ = ("L", "Q", "w", "key")

    def __init__(self, L, Q, w):
        self.L = L
        self.Q = tuple(sorted(Q))
        self.w = {M: wred(w[M], L) for M in w}
        self.key = (L, tuple(sorted((M, self.w[M]) for M in self.w)))

    def contains(self, el):
        M, v = el
        if M not in self.w:
            return False
        return in_lat(vsub(v, self.w[M]), self.L)


def cocycle_systems(G, Q, B):
    """All systems w: Q -> Q^2, w_M in v_M + Z^2 (mod B), satisfying the
    cocycle condition — i.e. all subgroups H with H ∩ T = B and image Q."""
    gens = min_gens(Q)
    Qset = set(Q)
    if not gens:
        return [{I2: ZERO}]
    box = lat_box(B)
    out = []
    for offsets in itertools.product(box, repeat=len(gens)):
        assign = {I2: ZERO}
        gen_els = [(g, vadd(G.ops[g], o)) for g, o in zip(gens, offsets)]
        ok = True
        frontier = [(I2, ZERO)]
        while frontier and ok:
            nxt = []
            for M1, w1 in frontier:
                for g, wg in gen_els:
                    M, w = gmul((g, wg), (M1, w1))
                    if M not in assign:
                        assign[M] = w
                        nxt.append((M, w))
                    elif not in_lat(vsub(assign[M], w), B):
                        ok = False
                        break
                if not ok:
                    break
            frontier = nxt
        if not ok or set(assign) != Qset:
            continue
        out.append(assign)
    return out


def subgroups_index_k(G, k):
    """All subgroups of index k in the wallpaper group G, deduplicated."""
    P = G.ops
    seen = {}
    for Q in point_subgroups(P.keys()):
        b = len(P) // len(Q)
        if k % b:
            continue
        a = k // b
        for B in sublattices(a):
            cols = lat_cols(B)
            if not all(in_lat(mvec(M, c), B) for M in Q for c in cols):
                continue
            for w in cocycle_systems(G, Q, B):
                s = Sub(B, Q, w)
                seen[s.key] = s
    return list(seen.values())


# ------------------------------------------------------- normaliser & orbits

def gl2_candidates(bound):
    rng = range(-bound, bound + 1)
    out = []
    for a, b, c, d in itertools.product(rng, repeat=4):
        if a * d - b * c in (1, -1):
            out.append(((a, b), (c, d)))
    return out


GL2_BOUND2 = gl2_candidates(2)
GRID_12 = [(F(i, 12), F(j, 12)) for i in range(12) for j in range(12)]


def normaliser_moves(G):
    """Generators of the affine normaliser of Gamma as moves (A, t): one
    compatible t per admissible A, every discrete Theta_I translation for
    A = I, and the integer translations e1, e2.  Continuous directions act
    trivially on subgroup data and are omitted."""
    moves = []
    for A in GL2_BOUND2:
        pairs = conj_pairs(G.ops, A, G.ops)
        if pairs is None:
            continue
        if A == I2:
            # all discrete solutions of (I - M) t ≡ 0 (mod Z^2)
            for t in GRID_12:
                if all(is_int(mvec(IM, t)[0] - rhs[0]) and
                       is_int(mvec(IM, t)[1] - rhs[1])
                       for IM, rhs in pairs):
                    moves.append((A, t))
        else:
            t = solve_cong(pairs)
            if t is not None:
                moves.append((A, t))
    moves.append((I2, (F(1), F(0))))
    moves.append((I2, (F(0), F(1))))
    return moves


def proper_equivalence_moves(G, moves):
    """Moves generating equivalence of colourings under PROPER affine maps.
    A pattern's own improper symmetries (reflections, glides) map the
    colouring to itself with the colours relabelled — conjugation by an
    element of Gamma is a recolouring, not a change of chirality — so inner
    conjugations join the proper normaliser moves.  A colouring is chiral
    iff its class splits when improper OUTER moves are withdrawn."""
    out = [(A, t) for A, t in moves if mdet(A) == 1]
    for M, v in G.ops.items():
        if mdet(M) == -1:
            out.append((M, v))
    return out


def apply_move(sub, move):
    A, t = move
    Ai = minv_uni(A)
    Lcols = lat_cols(sub.L)
    L2 = hnf_of([mvec(A, Lcols[0]), mvec(A, Lcols[1])])
    w2 = {}
    for M, w in sub.w.items():
        Mp = mmul(mmul(A, M), Ai)
        IM = ((1 - Mp[0][0], -Mp[0][1]), (-Mp[1][0], 1 - Mp[1][1]))
        w2[Mp] = vadd(mvec(A, w), mvec(IM, t))
    return Sub(L2, w2.keys(), w2)


def orbits(subs, moves):
    """Partition subgroup instances into orbits under the moves."""
    index = {s.key: s for s in subs}
    unseen = set(index)
    out = []
    while unseen:
        k0 = unseen.pop()
        orbit = {k0}
        frontier = [index[k0]]
        while frontier:
            nxt = []
            for s in frontier:
                for mv in moves:
                    s2 = apply_move(s, mv)
                    assert s2.key in index, "move left the subgroup family"
                    if s2.key not in orbit:
                        orbit.add(s2.key)
                        nxt.append(s2)
            frontier = nxt
        unseen -= orbit
        out.append(frozenset(orbit))
    return out


