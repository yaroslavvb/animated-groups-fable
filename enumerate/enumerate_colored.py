"""Colour groups of the plane: exact enumeration of the coloured 2D crystals.

A k-coloured plane crystal is a pair Gamma > H — a wallpaper group with a
subgroup of index k, the stabiliser of one colour — up to affine equivalence
of pairs (van der Waerden & Burckhardt 1961; Jarratt & Schwarzenberger 1980;
Wieting 1982).  Equivalently: a discrete subgroup of E(2) x S_k with faithful
crystallographic spatial projection, transitive on colours, up to
(affine) x (relabelling) conjugacy.  This module enumerates all of them for
k <= 6, entirely in exact rational arithmetic (pure Python, no dependencies
beyond exact.py), and emits render-ready data for the site.

ANCHOR: the per-group counts must reproduce Table 8.2.1 of Grünbaum &
Shephard, "Tilings and Patterns" (the periodic columns, from Wieting [1981])
= Jarratt & Schwarzenberger's Table 5:

    k:      2   3   4   5   6
    total  46  23  96  14  90     -> 269 coloured crystals in all.

The enumeration also computes, per class: the type of H and of the kernel
(colour-fixing) subgroup, the colour-permutation action, normality,
cyclicity (a clock can drive the colouring), and chirality under
PROPER-affine equivalence (the analogue of the 230-vs-219 distinction of
3D crystallography; the literature convention above allows reflections).

Representation.  Each of the 17 wallpaper groups Gamma is modelled with a
primitive translation lattice T = Z^2: Gamma = { (M | v_M + Z^2) }, point
matrices M in GL(2,Z) written in lattice coordinates, v_M in (1/2)Z^2.
A subgroup H of index k = a*b is the datum (L, Q, w): L = H ∩ T a sublattice
of index a, Q = the point-group image of H of index b in P (Q must preserve
L), and w: Q -> Q^2 a system of translation parts, w_M in v_M + Z^2, with the
cocycle condition w_{MN} ≡ w_M + M w_N (mod L).  Two subgroups give the same
coloured crystal iff they are conjugate under the affine normaliser of Gamma;
since conjugation must preserve T = Z^2, the normaliser is generated by
integer changes of basis A (A P A^{-1} = P, with a compatible translation)
and by translations, and orbits are computed by breadth-first closure.
Continuous normaliser directions satisfy (I - M) t = 0 for every M and act
trivially on the data, so a finite grid of rational translations suffices.
"""

