def enumerate_all(kmax=6, verbose=True):
    """Enumerate all colour-group classes for 2 <= k <= kmax."""
    results = []
    for hm in ORDER17:
        G = GROUPS[hm]
        moves = normaliser_moves(G)
        proper_moves = proper_equivalence_moves(G, moves)
        for k in range(2, kmax + 1):
            subs = subgroups_index_k(G, k)
            index = {s.key: s for s in subs}
            full = orbits(subs, moves)
            proper = orbits(subs, proper_moves)
            for orb in full:
                sub = index[sorted(orb)[0]]
                nprop = sum(1 for po in proper if po & orb)
                results.append({"hm": hm, "k": k, "sub": sub, "orbit": orb,
                                "properClasses": nprop})
            if verbose:
                exp = TABLE_8_2_1[hm][k - 2]
                mark = "OK" if len(full) == exp else "EXPECTED %d" % exp
                print("  %-5s k=%d  subgroups=%3d  classes=%2d  %s"
                      % (hm, k, len(subs), len(full), mark))
    return results


