def classify_with_map(ops):
    """Which of the 17 standard groups is (T=Z^2, ops) affinely equivalent
    to?  Returns (hm, A, t) with (A|t) ops (A|t)^{-1} = standard model;
    asserts uniqueness of the type."""
    finger = tuple(sorted((mdet(M), M[0][0] + M[1][1]) for M in ops))
    hits = []
    for g in GROUPS.values():
        if g.finger != finger:
            continue
        for A in GL2_BOUND3:
            pairs = conj_pairs(ops, A, g.ops)
            if pairs is None:
                continue
            t = solve_cong(pairs)
            if t is not None:
                hits.append((g.hm, A, t))
                break
    assert len(hits) == 1, ("classification not unique/found",
                            [h[0] for h in hits], ops)
    return hits[0]


def classify_concrete(ops):
    key = tuple(sorted(ops.items()))
    if key in _classify_cache:
        return _classify_cache[key]
    hm = classify_with_map(ops)[0]
    _classify_cache[key] = hm
    return hm


# ------------------------------------------------------------- coset actions

def coset_reps(G, sub, k):
    """BFS coset representatives of Gamma/H (exact elements)."""
    reps = [(I2, ZERO)]
    frontier = [(I2, ZERO)]
    gens = G.full_gens + [ginv(g) for g in G.full_gens]
    while frontier:
        nxt = []
        for r in frontier:
            for g in gens:
                e = gmul(g, r)
                if not any(sub.contains(gmul(ginv(rr), e)) for rr in reps):
                    reps.append(e)
                    nxt.append(e)
        frontier = nxt
    assert len(reps) == k, ("coset count", len(reps), k)
    return reps


def coset_index(sub, reps, el):
    for j, r in enumerate(reps):
        if sub.contains(gmul(ginv(r), el)):
            return j
    raise AssertionError("element in no coset")


def perm_of(G, sub, reps, el):
    return tuple(coset_index(sub, reps, gmul(el, r)) for r in reps)


def perm_mul(p, q):
    return tuple(p[q[i]] for i in range(len(p)))


def perm_group(perms, k):
    idp = tuple(range(k))
    S = {idp}
    frontier = [idp]
    while frontier:
        nxt = []
        for p in frontier:
            for q in perms:
                r = perm_mul(q, p)
                if r not in S:
                    S.add(r)
                    nxt.append(r)
        frontier = nxt
    return S


def perm_order(p):
    n = 1
    q = p
    idp = tuple(range(len(p)))
    while q != idp:
        q = perm_mul(p, q)
        n += 1
    return n


def action_label(S, k):
    """Name the transitive permutation group S <= S_k (k <= 6)."""
    n = len(S)
    maxo = max(perm_order(p) for p in S)
    cyclic = (maxo == n)
    abelian = all(perm_mul(p, q) == perm_mul(q, p) for p in S for q in S)
    if cyclic:
        return "C%d" % n
    if abelian and n == 4:
        return "C2×C2"
    if n == 6:
        return "S3"
    if n == 8:
        return "D4"
    if n == 10:
        return "D5"
    if n == 12:
        return "D6" if maxo == 6 else "A4"
    if n == 18:
        return "3²:2"
    if n == 20:
        return "F20"
    if n == 24:
        return "S4"
    if n == 36:
        return "S3×S3" if maxo == 6 else "3²:4"
    if n == 48:
        return "C2×S4"
    if n == 60:
        return "A5"
    if n == 72:
        return "S3≀C2"
    if n == 120:
        return "S5"
    if n == 720:
        return "S6"
    return "T%d" % n


# ------------------------------------------------------------------- kernels

def kernel_sub(G, sub, reps, k):
    """The colour-fixing subgroup K (kernel of the coset action) as a Sub."""
    idp = tuple(range(k))
    e1p = perm_of(G, sub, reps, (I2, (F(1), F(0))))
    e2p = perm_of(G, sub, reps, (I2, (F(0), F(1))))
    o1, o2 = perm_order(e1p), perm_order(e2p)
    vecs = [(o1, 0), (0, o2)]
    p1cur = idp
    for m1 in range(o1):
        p2cur = p1cur
        for m2 in range(o2):
            if (m1, m2) != (0, 0) and p2cur == idp:
                vecs.append((m1, m2))
            p2cur = perm_mul(e2p, p2cur)
        p1cur = perm_mul(e1p, p1cur)
    L0 = hnf_of(vecs)
    box0 = lat_box(L0)
    wk = {I2: ZERO}
    for M, v in G.ops.items():
        if M == I2:
            continue
        for o in box0:
            el = (M, vadd(v, o))
            if perm_of(G, sub, reps, el) == idp:
                wk[M] = el[1]
                break
    return Sub(L0, wk.keys(), wk)


# ---------------------------------------------------------------- rendering

def render_spec(G, sub, reps, k, kern):
    """Render data: one op per (point matrix, offset mod L0) with its colour;
    the renderer tiles the plane by the colour-period cell L0."""
    L0 = kern.L
    box0 = lat_box(L0)
    ops = []
    for M, v in G.ops.items():
        for o in box0:
            el = (M, vadd(v, o))
            ops.append({
                "M": [list(M[0]), list(M[1])],
                "v": [float(el[1][0]), float(el[1][1])],
                "color": coset_index(sub, reps, el),
            })
    # base point: maximise the minimum distance between orbit points of the
    # UNCOLOURED pattern (point images + integer translates) — floats only
    B = G.basis
    mats = [((float(M[0][0]), float(M[0][1])), (float(M[1][0]), float(M[1][1])),
             float(v[0]), float(v[1])) for M, v in G.ops.items()]
    shifts = [(i, j) for i in (-1, 0, 1) for j in (-1, 0, 1)]

    def cart(x, y):
        return (B[0][0] * x + B[1][0] * y, B[0][1] * x + B[1][1] * y)

    best = None
    for bx in range(0, 12):
        for by in range(0, 12):
            base = (bx / 12 + 0.031, by / 12 + 0.017)
            pts = []
            for (r0, r1, vx, vy) in mats:
                x = r0[0] * base[0] + r0[1] * base[1] + vx
                y = r1[0] * base[0] + r1[1] * base[1] + vy
                pts.append((x, y))
            dmin = None
            for i in range(len(pts)):
                for j in range(len(pts)):
                    for s1, s2 in shifts:
                        if i == j and s1 == 0 and s2 == 0:
                            continue
                        a = cart(pts[i][0] - pts[j][0] - s1, pts[i][1] - pts[j][1] - s2)
                        d = a[0] * a[0] + a[1] * a[1]
                        if dmin is None or d < dmin:
                            dmin = d
            if best is None or dmin > best[0]:
                best = (dmin, base)
    base = best[1]
    return {
        "basis": [[B[0][0], B[0][1]], [B[1][0], B[1][1]]],
        "cell": [list(lat_cols(L0)[0]), list(lat_cols(L0)[1])],
        "k": k,
        "ops": ops,
        "base": [base[0], base[1]],
        "minDist": math.sqrt(best[0]),
    }


# --------------------------------------------- the clockwork correspondence

def _fr(x):
    """Exact rational from a catalog float (everything sits on a 1/12 grid)."""
    f = F(x).limit_denominator(12)
    assert abs(float(f) - x) < 1e-9, x
    return f


def clockwork_pairs(catalog):
    """For every forward (clockwork) group in the site catalog, reconstruct
    the coloured pair in the spatial projection's own primitive coordinates:
    Gamma = the projection, H = the kernel of the clock phase, plus the
    clock order k.

    Catalog render ops are coset representatives modulo Z^2 x Z (integer
    spatial translations carry tau = 0), so the projection's translation
    lattice T_proj is Z^2 enlarged by any centring vectors (ops with M = I,
    v not in Z^2), and the clock phase is a homomorphism Gamma -> Z/k that
    is linear on T_proj."""
    out = []
    for g in catalog["groups"]:
        if not g["forward"]:
            continue
        ops = []
        for op in g["render"]["ops"]:
            assert op["s"] == 1, (g["id"], "forward group with reversal")
            M = ((op["M"][0][0], op["M"][0][1]), (op["M"][1][0], op["M"][1][1]))
            v = (_fr(op["v"][0]), _fr(op["v"][1]))
            tau = _fr(op["tau"]) % 1
            ops.append((M, v, tau))
        k = 1
        for _, _, tau in ops:
            k = k * tau.denominator // math.gcd(k, tau.denominator)
        if k == 1:
            out.append({"id": g["id"], "k": 1, "base": g["base"]})
            continue
        # T_proj = Z^2 + centring vectors, with the phase of each generator
        cents = [(v, tau) for M, v, tau in ops if M == I2]
        den = 1
        for v, _ in cents:
            for x in v:
                den = den * x.denominator // math.gcd(den, x.denominator)
        sup = hnf_of([(int(v[0] * den), int(v[1] * den)) for v, _ in cents]
                     + [(den, 0), (0, den)])
        b1 = (F(sup[0][0], den), F(0))
        b2 = (F(sup[0][1], den), F(sup[1][1], den))
        Bmat = ((b1[0], b2[0]), (b1[1], b2[1]))
        d = Bmat[0][0] * Bmat[1][1] - Bmat[0][1] * Bmat[1][0]
        Bi = ((Bmat[1][1] / d, -Bmat[0][1] / d),
              (-Bmat[1][0] / d, Bmat[0][0] / d))

        def phase_of_translation(b):
            """Clock phase of the T_proj vector b (original coordinates):
            0 on Z^2; on a centring coset, the centring's tau."""
            if is_int(b[0]) and is_int(b[1]):
                return F(0)
            for v, tau in cents:
                dd = vsub(b, v)
                if is_int(dd[0]) and is_int(dd[1]):
                    return tau
            raise AssertionError("translation not in T_proj")

        tau1 = phase_of_translation(b1)
        tau2 = phase_of_translation(b2)
        proj = {}
        taum = {}
        for M, v, tau in ops:
            Mp = mmul_frac(Bi, mmul_frac(M, Bmat))
            for row in Mp:
                for x in row:
                    assert is_int(x), (g["id"], "point matrix not integral")
            Mp = ((int(Mp[0][0]), int(Mp[0][1])), (int(Mp[1][0]), int(Mp[1][1])))
            vp = mvec(Bi, v)
            if Mp in proj:
                dd = vsub(proj[Mp], vp)
                assert is_int(dd[0]) and is_int(dd[1]), (g["id"], "coset clash")
                continue
            proj[Mp] = vmod1(vp)
            # rebase the op's tau to the canonical representative vmod1(vp):
            # subtracting the integer part n (in T_proj coords) shifts tau
            # by -phase(n) = -(n1 tau1 + n2 tau2)
            n = vsub(vp, vmod1(vp))
            taum[Mp] = (tau - n[0] * tau1 - n[1] * tau2) % 1
        out.append({"id": g["id"], "k": k, "base": g["base"],
                    "proj": proj, "taum": taum, "tau12": (tau1, tau2)})
    return out


def match_clockwork(results, catalog):
    """Assign to each nontrivial clockwork group its coloured-crystal class.
    Returns {gid: coloredId} and fills r['clockwork']."""
    by_key = {}
    for r in results:
        for kk in r["orbit"]:
            by_key[(r["hm"], r["k"], kk)] = r
    for r in results:
        r["clockwork"] = []
    pairs = clockwork_pairs(catalog)
    trivial = [p for p in pairs if p["k"] == 1]
    assert len(trivial) == 17, len(trivial)
    out = {}
    for p in pairs:
        if p["k"] == 1:
            continue
        k = p["k"]
        tau1, tau2 = p["tau12"]
        # kernel H = ker(phase): translation lattice first
        vecs = [(k, 0), (0, k)]
        for m1 in range(k):
            for m2 in range(k):
                if (m1, m2) != (0, 0) and (m1 * tau1 + m2 * tau2) % 1 == 0:
                    vecs.append((m1, m2))
        Lproj = hnf_of(vecs)
        # point part: for each coset (M | vp) find n with
        # tau(M) + n1 tau1 + n2 tau2 ≡ 0 (mod 1)
        wk = {}
        for M, vp in p["proj"].items():
            for n1 in range(k):
                for n2 in range(k):
                    if (p["taum"][M] + n1 * tau1 + n2 * tau2) % 1 == 0:
                        wk[M] = vadd(vp, (F(n1), F(n2)))
                        break
                else:
                    continue
                break
        # move the pair onto the standard model of its type
        hm, A, t = classify_with_map(p["proj"])
        assert hm == p["base"], (p["id"], hm, p["base"])
        Ai = minv_uni(A)
        w2 = {}
        for M, w in wk.items():
            Mp = mmul(mmul(A, M), Ai)
            IM = ((1 - Mp[0][0], -Mp[0][1]), (-Mp[1][0], 1 - Mp[1][1]))
            w2[Mp] = vadd(mvec(A, w), mvec(IM, t))
        Lcols = lat_cols(Lproj)
        Lstd = hnf_of([mvec(A, Lcols[0]), mvec(A, Lcols[1])])
        sub = Sub(Lstd, w2.keys(), w2)
        key = (hm, k, sub.key)
        assert key in by_key, (p["id"], "pair not found among enumerated")
        r = by_key[key]
        assert r["cyclic"] and r["k"] == k, (p["id"], r["id"])
        r["clockwork"].append(p["id"])
        out[p["id"]] = r["id"]
    ncls = len(set(out.values()))
    print("clockwork matching: 17 trivial (k=1), %d nontrivial -> %d "
          "coloured classes" % (len(out), ncls))
    return out


